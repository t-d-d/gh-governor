/**
 * Who a PR or an issue body says hears of it.
 *
 * A PR or an issue a session wrote ends in the Claude Code footer and that
 * session's link, or in the link alone where the GitHub tool stripped the
 * footer: its owner, subscribed to every event but labels,
 * and on an issue but deploys, as the standing line counts it. A
 * label carries no text, so nothing names the session that set it, and a
 * filer that labels its own issue would be told of it; a filer that wants
 * labels adds a line for them. Any other session, a
 * reviewer or one elaborating an issue, subscribes by adding one line to the
 * body, which renders as nothing:
 *
 *   <!-- governor:subscribe https://claude.ai/code/session_… events=comments,reviews -->
 *
 * and unsubscribes by removing it; the dispatcher removes it for a session
 * that refuses a message (archived). An owner link stays when its session
 * refuses, an issue's as a PR's. `events` absent means every one. The
 * vocabulary is closed (`SUBSCRIPTION_EVENTS`, fire.mjs): an event it does not
 * know subscribes to nothing.
 *
 * A session's post ends in the footer. Where the session signed it, with its
 * link under the footer or alone on the line above it ({@link postedBy}), a
 * subscriber is never messaged with what it wrote itself. Claude Code adds
 * no link to a comment, so a session signs only when told to (`SIGN_POSTS`,
 * fire.mjs). A post with the footer and no link is some session's, and
 * reaches every subscriber, told it may be its own (mention.mjs).
 *
 * Pure, importing only the fire's vocabulary (fire.mjs) and the copied
 * markdown parser (vendor/commonmark.cjs): the receiver
 * (mention.mjs, route.mjs) and the task (dispatch/deliveries.mjs,
 * dispatch/workflow.mjs, and the standing search in
 * scripts/lib/github-app.mjs; the image copies both files) read bodies with it.
 */

import { SESSION_LINK as LINK, SUBSCRIPTION_EVENTS, lets } from './fire.mjs';
import commonmark from './vendor/commonmark.cjs';

/** @typedef {import('./fire.mjs').SubscriptionEvent} SubscriptionEvent */

/**
 * The body of an issue or PR as governor reads sessions from it to route
 * text into them: the body, where `relay`, the repo's `trust.relay`, lets
 * its author in; else the empty body, which names no session and
 * subscribes no one. The one gate between a body and the readers below
 * ({@link sessionNamedIn}, {@link subscribersFor}, {@link sessionsNamedIn})
 * wherever governor routes by them: anyone can open an issue on a public
 * repo, and session links are public on every PR a session wrote, so a
 * stranger's body that names a session would otherwise route owners'
 * comments and events into it. A body whose author was not read is
 * `NONE`'s.
 *
 * @param {{ body?: unknown } & import('./fire.mjs').Author} on
 * @param {readonly string[]} relay
 * @returns {string}
 */
export const relayedBody = (on, relay) => (lets(relay, on) ? String(on.body ?? '') : '');

const KNOWN = new Set(/** @type {readonly string[]} */ (SUBSCRIPTION_EVENTS));

/**
 * A session link in a body, not glued to more id characters, which would cut
 * an id the CLI does not know out of one it might.
 */
const SESSION_LINK = new RegExp(`${LINK.source}(?![A-Za-z0-9_-])`, 'g');

/** The same link, as the whole of a subscribe line's session. */
const WHOLE_LINK = new RegExp(`^${LINK.source}$`);

/** The Claude Code footer, in either shape a session's PR body ends with. */
const CLAUDE_CODE = '[Claude Code]';

/** The footer every comment a session posts ends with. */
const SESSION_FOOTER = '_Generated by [Claude Code](https://claude.ai/code';

/** One subscribe line, with the newline before it where there is one. */
const LINE = /\n?<!--[ \t]*governor:subscribe[ \t]+(\S+)(?:[ \t]+events=(\S*))?[ \t]*-->/g;

/**
 * `text` with every subscribe line blanked, character for character, so a
 * line added below the footer never reads as the owner and an index into
 * the result is one into `text`.
 *
 * @param {string} text
 */
const withoutLines = (text) => text.replace(LINE, (line) => line.replace(/[^\n]/g, ' '));

/**
 * Each line of `text`, as CommonMark splits it at a line feed, a carriage
 * return, or the two together: where it starts and where it ends, its line
 * ending left out.
 *
 * @param {string} text
 * @returns {Array<[number, number]>}
 */
const lineSpans = (text) => {
  /** @type {Array<[number, number]>} */
  const spans = [];
  let start = 0;
  for (const ending of text.matchAll(/\r\n|\r|\n/g)) {
    spans.push([start, ending.index]);
    start = ending.index + ending[0].length;
  }
  spans.push([start, text.length]);
  return spans;
};

/**
 * The longest body the receiver reads quotes in, in characters: GitHub's own
 * cap on a comment's, an issue's or a PR's body.
 */
export const BODY_READ_LIMIT = 65536;

/**
 * The most lists and blockquotes the receiver lets one line open. The
 * parser's time for a line grows with the square of the containers it
 * opens: `- ` 16,000 times on one line took seconds. No body a person
 * writes opens more than a few.
 */
export const NESTING_READ_LIMIT = 32;

/**
 * One list item or blockquote opened on a line: a `>`, or a list marker
 * followed by a space, a tab or the line's end. Counted from a line's
 * start while each follows the last, so it may count more than the parser
 * opens, never fewer.
 */
const OPENER = /[ \t]*(?:>|(?:[-+*]|\d{1,9}[.)])(?=[ \t\r\n]|$))/y;

/**
 * A line that is a thematic break of `-` or `*`, three or more with only
 * spaces between. CommonMark reads such a line as a rule before a list, so
 * it opens nothing, however many markers it holds.
 */
const RULE = / {0,3}([-*])(?:[ \t]*\1){2,}[ \t]*(?=[\r\n]|$)/y;

/**
 * How many characters `text` holds, as GitHub counts toward its cap: code
 * points, so an emoji is one, not two UTF-16 code units.
 *
 * @param {string} text
 */
const characters = (text) => {
  let count = 0;
  for (const _ of text) count += 1;
  return count;
};

/**
 * Whether `text` is too long or too deeply nested to read for quotes in
 * time: longer than {@link BODY_READ_LIMIT} characters, or with a line that opens more
 * than {@link NESTING_READ_LIMIT} lists and blockquotes. Such a body is read
 * as quoted whole, so nothing in it summons or names a session: a body built
 * to be slow is never a real summons, and a live link dropped costs a person
 * one more comment, while a quoted link read as live sends text where nobody
 * meant it. Time linear in the body.
 *
 * @param {string} text
 */
export const pastReadingBound = (text) => pastBound(text, lineSpans(text));

/**
 * {@link pastReadingBound}, given the spans of `text`'s lines.
 *
 * @param {string} text
 * @param {Array<[number, number]>} lines
 */
const pastBound = (text, lines) => {
  if (text.length > BODY_READ_LIMIT && (text.length > 2 * BODY_READ_LIMIT || characters(text) > BODY_READ_LIMIT)) return true;
  for (const [start, end] of lines) {
    RULE.lastIndex = start;
    if (RULE.test(text)) continue;
    let opened = 0;
    OPENER.lastIndex = start;
    while (OPENER.lastIndex < end && OPENER.test(text)) {
      opened += 1;
      if (opened > NESTING_READ_LIMIT) return true;
    }
  }
  return false;
};

/**
 * The spans of the lines of `text` that render inside a blockquote, as
 * commonmark.js reads it (vendor/README.md): every line in the source range
 * of a blockquote, or of any block inside one. A line of only spaces is
 * left as it is. A body {@link pastReadingBound} is not parsed: every line
 * of it is quoted.
 *
 * @param {string} text
 * @returns {Array<[number, number]>}
 */
const quotedSpans = (text) => {
  const lines = lineSpans(text);
  if (pastBound(text, lines)) return lines.filter(([start, end]) => text.slice(start, end).trim() !== '');
  // Each block's range raises the count from its first line and lowers it
  // after its last, so a line deep in many nested quotes costs one step,
  // not one per quote around it.
  const opened = new Int32Array(lines.length + 1);
  const parser = new commonmark.Parser();
  // Only the blocks' lines are read: the text inside a paragraph or a heading is not.
  parser.processInlines = () => {};
  const walker = parser.parse(text).walker();
  let depth = 0;
  for (let step = walker.next(); step; step = walker.next()) {
    const { node, entering } = step;
    if (node.type === 'block_quote') depth += entering ? 1 : -1;
    if (!entering || depth === 0 || !node.sourcepos) continue;
    const [[first], [last]] = node.sourcepos;
    opened[first - 1] = (opened[first - 1] ?? 0) + 1;
    opened[last] = (opened[last] ?? 0) - 1;
  }
  let open = 0;
  return lines.filter(([start, end], i) => {
    open += opened[i] ?? 0;
    return open > 0 && text.slice(start, end).trim() !== '';
  });
};

/** How many bodies {@link spansOf} keeps: a remark and the PR or issue it is on, and a few to spare. */
const KEPT_READS = 4;

/**
 * The bodies read last and their quoted spans, the latest last. The
 * receiver reads a remark and the body of the PR it is on in turn, many
 * times each, so each is parsed once, not once per reader.
 *
 * @type {Map<string, Array<[number, number]>>}
 */
const lastReads = new Map();

/** {@link quotedSpans}, for a body read lately without a second parse. @param {string} text */
const spansOf = (text) => {
  let spans = lastReads.get(text);
  if (spans === undefined) {
    spans = quotedSpans(text);
    if (lastReads.size >= KEPT_READS) lastReads.delete(lastReads.keys().next().value ?? '');
  }
  lastReads.delete(text);
  lastReads.set(text, spans);
  return spans;
};

/**
 * `text` with every quoted line replaced by `fill`, character for
 * character, so an index into the result is one into `text`. A line ending
 * is kept.
 *
 * @param {string} text
 * @param {string} fill
 */
const fillQuotes = (text, fill) => {
  let out = '';
  let at = 0;
  for (const [start, end] of spansOf(text)) {
    out += text.slice(at, start) + fill.repeat(end - start);
    at = end;
  }
  return out + text.slice(at);
};

/** `text` with every quoted line blanked, character for character. @param {string} text */
export const withoutQuotes = (text) => fillQuotes(text, ' ');

/**
 * `text` as an owner link is read from it: subscribe lines blanked, and
 * blockquotes filled with `>`, character for character. A member's body
 * quoting a session's footer and link is the member's, not that session's.
 * A quote is filled, not blanked, because it is still a line of text: a
 * link a member cites above a quote is not alone on the last line.
 *
 * @param {string} text
 */
const ownerText = (text) => withoutLines(fillQuotes(text, '>'));

/** The GitHub tool's footer, naming no session, with nothing after it. */
const TRAILING_TOOL_FOOTER = /_Generated by \[Claude Code\]\(https:\/\/claude\.ai\/code\)_\s*$/;

/**
 * The last session link in `text` at or after index `from`, with its index,
 * or undefined.
 *
 * @param {string} text
 * @param {number} from a footer's index, or -1 for none
 */
const lastLinkFrom = (text, from) => {
  if (from === -1) return undefined;
  const last = [...text.slice(from).matchAll(SESSION_LINK)].at(-1);
  return last?.index === undefined ? undefined : { link: last[0], at: from + last.index };
};

/**
 * `masked` without the trailing footers of the GitHub tool, which a
 * session's edit of a body appends naming no session.
 *
 * @param {string} masked
 */
const withoutToolFooters = (masked) => {
  let kept = masked;
  for (let tail = TRAILING_TOOL_FOOTER.exec(kept); tail; tail = TRAILING_TOOL_FOOTER.exec(kept)) kept = kept.slice(0, tail.index);
  return kept;
};

/**
 * The last session link under the last Claude Code footer of `kept`, with
 * its index, or undefined. Any "[Claude Code]" is the footer, so a citation
 * above it stays a citation.
 *
 * @param {string} kept the body, subscribe lines blanked and trailing tool footers cut
 */
const footerLink = (kept) => lastLinkFrom(kept, kept.lastIndexOf(CLAUDE_CODE));

/**
 * A label a session may write before its link on its signature line, once
 * emphasis is left out, in any case: `Session:`, `Claude-Session:`,
 * `Claude Code session:` or `Session link:`.
 */
const LABEL = /^(?:claude[- ]?(?:code[- ]?)?)?session(?:[- ]?link)?:$/i;

/**
 * A line holding a session link: the text before it, the link as a
 * Markdown link's target, in angle brackets or bare, and the text after it.
 * A bare link may end in an underscore that closes emphasis, but not one
 * glued to more id characters.
 */
const LINKED_LINE = new RegExp(`^(.*?)(?:\\[[^\\]\\n]*\\]\\((${LINK.source})\\)|<(${LINK.source})>|(${LINK.source})(?![A-Za-z0-9-]|_[A-Za-z0-9]))(.*)$`);

/**
 * The session link `line` is a signature of, or undefined: a link alone on
 * its line, which may also carry whitespace, angle brackets, a Markdown
 * link whose target is the link, emphasis, a trailing full stop, or a
 * {@link LABEL} before it. A link with other words around it is a citation.
 *
 * @param {string} line
 * @returns {string | undefined}
 */
const signedLine = (line) => {
  const match = LINKED_LINE.exec(line);
  if (match === null) return undefined;
  const before = String(match[1]).replace(/[*_]/g, '').trim();
  const after = String(match[5]).replace(/[*_]/g, '').trim();
  if ((before !== '' && !LABEL.test(before)) || (after !== '' && after !== '.')) return undefined;
  return match[2] ?? match[3] ?? match[4];
};

/**
 * The signature line of `text`: the last line with more on it than a rule
 * or a Claude Code footer line ({@link FOOTER_LINE}), where that line is a
 * {@link signedLine}. Its link, the link's index, and the line's span; or
 * undefined. So a session's link is read just above either footer, just
 * under it, between two footers, and on the last line.
 *
 * @param {string} text the body, subscribe lines blanked and quotes filled
 * @returns {Owner | undefined}
 */
const signatureLink = (text) => {
  const lines = lineSpans(text);
  for (let i = lines.length - 1; i >= 0; i -= 1) {
    const [start, end] = /** @type {[number, number]} */ (lines[i]);
    const line = text.slice(start, end);
    const bare = line.trim();
    if (RULE_OR_BLANK.test(bare) || FOOTER_LINE.test(bare)) continue;
    const link = signedLine(line);
    return link === undefined ? undefined : { link, at: start + line.indexOf(link), line: [start, end] };
  }
  return undefined;
};

/**
 * `found` with the span of its line where that line is a signature
 * ({@link signedLine}) of the link, so a writer replaces or removes the
 * line as written, not just the URL in it.
 *
 * @param {string} text
 * @param {{ link: string, at: number }} found
 * @returns {Owner}
 */
const withLine = (text, found) => {
  const span = lineSpans(text).find(([start, end]) => start <= found.at && found.at < end);
  return span !== undefined && signedLine(text.slice(...span)) === found.link ? { ...found, line: span } : found;
};

/**
 * @typedef {{ link: string, at: number, line?: [number, number] }} Owner
 * An owner link, its index, and, where it is a signature line, that line's span.
 */

/**
 * The owner link of an issue's or a PR's body: the last link under its last
 * Claude Code footer, or, with none there, its signature line
 * ({@link signatureLink}). A trailing footer of the GitHub tool is passed
 * over. `mcp__github__issue_write` strips the footer from an issue body and
 * puts none back, which leaves the filer's link on the last line alone.
 *
 * @param {string} masked the body, subscribe lines blanked
 * @returns {Owner | undefined}
 */
const ownerLink = (masked) => {
  const kept = withoutToolFooters(masked);
  const under = footerLink(kept);
  return under === undefined ? signatureLink(kept) : withLine(kept, under);
};

/**
 * The session a body names: its last session link under the last Claude
 * Code footer, or, with no link there, its signature line: a link alone on
 * its line, with nothing below it but blank lines, rules and footer lines
 * in either shape ({@link signatureLink}); or null. A subscribe line names a subscriber, not this. Last, because a body that cites an earlier session
 * ("supersedes …") still ends in its own footer; under the footer or alone
 * on a line at the end, because a person's PR that cites a session in its text
 * is not that session's. A link or footer inside a quote is never read: a
 * member's body quoting a session's post is not that session's. On a PR or
 * an issue it is the owner.
 *
 * @param {unknown} body
 * @returns {string | null}
 */
export const sessionNamedIn = (body) => ownerLink(ownerText(String(body ?? '')))?.link ?? null;

/**
 * A takeover's line that its launch printed no session link: a sentence a
 * person reads, then the time in a comment the takeover reads back. The
 * sentence comes first: a line that opens with a comment is an HTML block,
 * and GitHub would show the sentence after it raw. The whole line is
 * governor's, and goes with the marker, newline and all.
 */
const OWNER_UNKNOWN = /[^\n]*<!--[ \t]*governor:owner-unknown[ \t]+(\S+)[ \t]*-->[^\n]*(?:\n|$)/g;

/**
 * The body with every owner-unknown line removed.
 *
 * @param {unknown} body
 */
const withoutOwnerUnknown = (body) => String(body ?? '').replace(OWNER_UNKNOWN, '');

/**
 * When a takeover's launch last printed no session link, as the body's
 * owner-unknown line says, or null. A line inside a quote is not read, nor
 * one whose time does not parse.
 *
 * @param {unknown} body
 * @returns {string | null}
 */
export const ownerUnknownSince = (body) => {
  const at = [...withoutQuotes(String(body ?? '')).matchAll(OWNER_UNKNOWN)].at(-1)?.[1];
  return at === undefined || Number.isNaN(Date.parse(at)) ? null : at;
};

/**
 * The body with one line saying a takeover at `at` printed no session link,
 * in place of any earlier one. The owner link stays where it is, so the
 * body routes to the same session as before: the line goes just above the
 * line that holds the owner link, or at the end where there is none.
 * {@link relinkSession} removes it. Throws for a body
 * {@link pastReadingBound}, where no line written would be read.
 *
 * @param {unknown} body
 * @param {string} at an ISO time
 * @returns {string}
 */
export const markOwnerUnknown = (body, at) => {
  const text = withoutOwnerUnknown(body);
  if (pastReadingBound(text)) throw new Error('the body is too long or too deeply nested to read, so no owner-unknown line written into it would be read');
  const line = `_Governor took this PR over at ${at}, but the launch printed no session link, so this PR's session is not known._ <!-- governor:owner-unknown ${at} -->`;
  const owner = ownerLink(ownerText(text));
  if (!owner) return `${text.trimEnd()}${text.trim() ? '\n\n' : ''}${line}`;
  const start = text.lastIndexOf('\n', owner.at) + 1;
  return `${text.slice(0, start)}${line}\n${text.slice(start)}`;
};

/**
 * The body with `sessionUrl` where {@link sessionNamedIn} reads it: in place
 * of the owner link, on a signature line however it is written; under a footer
 * naming none, appended; with no footer, in one appended. Any owner-unknown
 * line goes ({@link markOwnerUnknown}). A fallback's handoff
 * (dispatch/deliveries.mjs). Throws for a body {@link pastReadingBound},
 * which names no session whatever is written into it.
 *
 * @param {unknown} body
 * @param {string} sessionUrl
 * @returns {string}
 */
export const relinkSession = (body, sessionUrl) => {
  const text = withoutOwnerUnknown(body);
  // Such a body reads as quoted whole, so no link written into it would name a session.
  if (pastReadingBound(text)) throw new Error('the body is too long or too deeply nested to read for its session link, so no link written into it would name a session');
  const masked = ownerText(text);
  const owner = ownerLink(masked);
  if (owner?.line) {
    const [start, end] = owner.line;
    return `${text.slice(0, start)}${text.slice(start, end).split(owner.link).join(sessionUrl)}${text.slice(end)}`;
  }
  if (owner) return `${text.slice(0, owner.at)}${sessionUrl}${text.slice(owner.at + owner.link.length)}`;
  const kept = text.trimEnd();
  if (masked.includes(CLAUDE_CODE)) return `${kept}\n\n${sessionUrl}`;
  return `${kept}${kept ? '\n\n' : ''}🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n${sessionUrl}`;
};

/**
 * The body with its owner link, as {@link sessionNamedIn} reads it,
 * removed, and every other character kept: a signature line goes whole,
 * however it is written, with the blank line before it. A body that names no owner
 * is returned as it is. Governor removes the link of a session that may
 * not own an issue, a builder or a session that edited a person's issue
 * (dispatch/take.mjs). With `footer`, a Claude Code footer left signing
 * nothing goes too, with the rules above it: a person's issue the editor
 * signed would otherwise read as a session's unsigned post
 * ({@link unsignedSessionBody}), which any session may take. Throws for a
 * body {@link pastReadingBound}.
 *
 * @param {unknown} body
 * @param {{ footer?: boolean }} [options]
 * @returns {string}
 */
export const unlinkSession = (body, { footer = false } = {}) => {
  const unlinked = unlinkOwner(body);
  return footer ? withoutUnsignedFooter(unlinked) : unlinked;
};

/**
 * The body with its owner link removed ({@link unlinkSession}).
 *
 * @param {unknown} body
 * @returns {string}
 */
const unlinkOwner = (body) => {
  const text = String(body ?? '');
  if (pastReadingBound(text)) throw new Error('the body is too long or too deeply nested to read for its session link');
  const owner = ownerLink(ownerText(text));
  if (!owner) return text;
  if (owner.line === undefined) return `${text.slice(0, owner.at)}${text.slice(owner.at + owner.link.length)}`;
  const [start, end] = owner.line;
  const before = text.slice(0, start).replace(/\s+$/, '');
  const after = text.slice(end).replace(/^\s*\n/, '');
  if (after.trim() === '') return before;
  return before === '' ? after : `${before}\n\n${after}`;
};

/**
 * Whether `body`, an issue's, is a session's unsigned post: its last line
 * with text on it, past any rule, outside any quote and subscribe line, is
 * the Claude Code footer, and it names no session ({@link sessionNamedIn}). A session
 * filed it without signing it, so the issue has no owner. A body with no
 * footer and no session is a person's, and the person owns it.
 *
 * @param {unknown} body
 * @returns {boolean}
 */
export const unsignedSessionBody = (body) => {
  const masked = ownerText(String(body ?? ''));
  if (ownerLink(masked) !== undefined) return false;
  const last = masked.split('\n').map((line) => line.trim()).filter((line) => !RULE_OR_BLANK.test(line)).at(-1) ?? '';
  return FOOTER_LINE.test(last);
};

/** A line with nothing on it but a rule, or nothing at all. */
const RULE_OR_BLANK = /^[\s*_-]*$/;

/**
 * `text` without the footer that ends a session's unsigned post, nor the
 * rules and blank lines above it. Any other body is returned as it is.
 *
 * @param {string} text
 * @returns {string}
 */
const withoutUnsignedFooter = (text) => {
  if (!unsignedSessionBody(text)) return text;
  const lines = ownerText(text).split('\n');
  let last = lines.length - 1;
  while (last > 0 && RULE_OR_BLANK.test((lines[last] ?? '').trim())) last -= 1;
  let kept = text.split('\n').slice(0, last);
  while (kept.length > 0 && RULE_OR_BLANK.test((kept.at(-1) ?? '').trim())) kept = kept.slice(0, -1);
  return kept.join('\n');
};

/**
 * The whole of a Claude Code footer line, in either shape a session's body
 * ends with: the comment footer, or a PR body's attribution line. A line
 * that only mentions Claude Code is a person's words.
 */
const FOOTER_LINE = /^(?:🤖\s*)?_?Generated (?:by|with) \[Claude Code\]\([^)\s]*\)_?$/u;

/**
 * Whether a session posted `body`: the footer, or a session link under the
 * Claude Code attribution.
 *
 * @param {unknown} body
 */
export const isSessionPost = (body) => String(body ?? '').includes(SESSION_FOOTER) || footerLink(withoutToolFooters(withoutLines(String(body ?? '')))) !== undefined;

/**
 * The session that posted `body`, or null: its URL under the last Claude
 * Code footer, or its signature line, read as a body's is
 * ({@link signatureLink}), on a post that carries a footer line in either
 * shape. The posting tool strips a footer it finds and appends its own, so
 * a session signs just above it. A post with no footer is a person's,
 * though a session link ends it: a person pasting a session's link is
 * still heard by that session. A session cited in the text, or a post
 * quoted in a reply, is not the poster.
 *
 * @param {unknown} body
 * @returns {string | null}
 */
export const postedBy = (body) => {
  const text = ownerText(String(body ?? ''));
  const under = lastLinkFrom(text, text.lastIndexOf(CLAUDE_CODE));
  if (under) return under.link;
  if (!text.split(/\r\n|\r|\n/).some((line) => FOOTER_LINE.test(line.trim()))) return null;
  return signatureLink(text)?.link ?? null;
};

/**
 * Whether a session posted `body` and did not sign it: the footer outside
 * any quote, and no {@link postedBy}. A person's reply quoting a session's
 * post is the person's.
 *
 * @param {unknown} body
 */
export const unsignedPost = (body) => withoutLines(withoutQuotes(String(body ?? ''))).includes(SESSION_FOOTER) && postedBy(body) === null;

/**
 * Whether a session posted `body` itself: {@link isSessionPost} read
 * outside any quote. A person's reply quoting a session's post is the
 * person's.
 *
 * @param {unknown} body
 */
export const ownSessionPost = (body) => isSessionPost(withoutQuotes(String(body ?? '')));

/** A session's id, off its claude.ai/code URL or as given. @param {string} session */
export const sessionId = (session) => session.slice(session.lastIndexOf('/') + 1);

/** Whether two names (URL or id) are one session. @param {string} a @param {string} b */
export const sameSession = (a, b) => sessionId(a) === sessionId(b);

/**
 * The line that subscribes `session`, to `events` or to all of them.
 *
 * @param {string} session
 * @param {readonly SubscriptionEvent[]} [events]
 */
export const subscribeLine = (session, events) =>
  `<!-- governor:subscribe ${session}${events ? ` events=${events.join(',')}` : ''} -->`;

/**
 * Every subscribe line in `body`: the session, and the events it asked for
 * (null for all). A line whose session is not a whole session link is none.
 *
 * @param {unknown} body
 * @returns {Array<{ session: string, events: ReadonlySet<string> | null }>}
 */
const linesIn = (body) =>
  [...String(body ?? '').matchAll(LINE)]
    .filter((m) => WHOLE_LINK.test(String(m[1])))
    .map((m) => ({
      session: String(m[1]),
      events: m[2] === undefined ? null : new Set(m[2].split(',').filter((e) => KNOWN.has(e))),
    }));

/**
 * The ids of the sessions `body` names as its owner ({@link sessionNamedIn})
 * or in a subscribe line: the sessions whose standing line counts it. A
 * session's link quoted or cited in a member's text is not one of them.
 *
 * @param {unknown} body
 * @returns {Set<string>}
 */
export const sessionsNamedIn = (body) => {
  const owner = sessionNamedIn(body);
  return new Set([...(owner === null ? [] : [owner]), ...linesIn(body).map((line) => line.session)].map(sessionId));
};

/**
 * Who hears of `event` on the PR or issue whose body is `body`: the owner
 * its footer names first, unless the event is `labels`, or `deploys` on an
 * issue (`issue`), then each session a line subscribes to it, once each.
 * The owner's own line keeps it the owner.
 *
 * @param {unknown} body
 * @param {SubscriptionEvent} event
 * @param {{ issue?: boolean }} [on] `issue`: the body is an issue's, not a PR's.
 * @returns {Array<{ session: string, owner: boolean }>}
 */
export const subscribersFor = (body, event, { issue = false } = {}) => {
  const named = sessionNamedIn(body);
  const lineOnly = event === 'labels' || (issue && event === 'deploys');
  /** @type {Array<{ session: string, owner: boolean }>} */
  const subscribers = named === null || lineOnly ? [] : [{ session: named, owner: true }];
  for (const line of linesIn(body)) {
    if (line.events !== null && !line.events.has(event)) continue;
    if (subscribers.some((s) => sameSession(s.session, line.session))) continue;
    subscribers.push({ session: line.session, owner: named !== null && sameSession(named, line.session) });
  }
  return subscribers;
};

/**
 * The body with every line subscribing `session` removed. The owner's
 * footer is not a line, and stays.
 *
 * @param {unknown} body
 * @param {string} session
 * @returns {string}
 */
export const unsubscribe = (body, session) =>
  String(body ?? '').replace(LINE, (line, named) => (WHOLE_LINK.test(named) && sameSession(named, session) ? '' : line));
