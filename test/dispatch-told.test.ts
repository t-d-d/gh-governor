/**
 * Governor's own comments on an issue are records for people, and the relay
 * sends them to nobody (#565, under PRD #535). The turn that posts one tells
 * the roles that should hear it (dispatch/told.mjs): a wait warning, a fix
 * only the spec owner can make, tells the spec owner once, when it is
 * posted. The wait ticket's full comment tells nobody.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { TOLD, specOwnerNote, specOwnerTeller, tellerFor, unmarked } from '../dispatch/told.mjs';
import { WAIT_FULL_MARKER, WAIT_UNLINED_MARKER, WAIT_UNREADABLE_MARKER, repairRelative, reportUnreadable, waitLinks, waitRelativeMarker } from '../dispatch/waits.mjs';

const REPO = 'acme/factory';
const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';

type Logged = Record<string, unknown>;
type Told = { issue: number, comment: string };

const logs = () => {
  const logged: Logged[] = [];
  return { logged, log: (event: string, context: Record<string, unknown> = {}) => { logged.push({ event, ...context }); } };
};

/** A tell that records what it was asked to tell. */
const recorder = () => {
  const told: Told[] = [];
  return { told, tell: async (issue: number, comment: string) => { told.push({ issue, comment }); } };
};

const delivered = (over: Record<string, unknown> = {}) => ({ ok: true, answered: true, refused: false, sessionUrl: SPEC, error: null, fallback: null, dropped: null, skipped: null, relinked: null, ...over });

describe('the spec owner\'s message of governor\'s comment', () => {
  test('quotes the comment without governor\'s markers, and says the fix is the spec owner\'s', () => {
    const note = specOwnerNote(7, `Governor cannot read the date.\n\n${WAIT_UNREADABLE_MARKER}`);
    assert.match(note, /^Governor commented on #7:\n\nGovernor cannot read the date\.\n\n/);
    assert.doesNotMatch(note, /<!--/);
    assert.match(note, /You are #7's spec owner/);
    assert.equal(unmarked(`a\n\n${waitRelativeMarker('#3')}`), 'a');
  });

  test('goes to the session the ticket\'s body names, read under trust.relay, once', async () => {
    const sent: Array<{ session: string, text: string, issue: number, dropFrom: number[] }> = [];
    const { log } = logs();
    const tell = specOwnerTeller({
      read: async () => ({ body: `The spec.\n\n${SPEC}${FOOTER}`, author: 't-d-d', association: 'OWNER' }),
      relay: ['OWNER'],
      deliver: async (session, text, { on, dropFrom }) => { sent.push({ session, text, issue: on[0]!, dropFrom }); return delivered() as never; },
      log,
      repo: REPO,
    });
    await tell(7, 'The comment.');
    assert.deepEqual(sent.map((s) => [s.session, s.issue]), [[SPEC, 7]]);
    assert.deepEqual(sent[0]!.dropFrom, [7], 'an archived spec owner leaves the ticket\'s subscribe line, as a relayed message did');
    assert.match(sent[0]!.text, /The comment\./);
  });

  test('a body naming no session, or one trust.relay leaves out, tells nobody', async () => {
    for (const row of [{ body: 'A person wrote this.', association: 'OWNER' }, { body: `The spec.\n\n${SPEC}`, association: 'NONE' }]) {
      const sent: string[] = [];
      const { log, logged } = logs();
      const tell = specOwnerTeller({ read: async () => row, relay: ['OWNER'], deliver: async (session) => { sent.push(session); return delivered() as never; }, log, repo: REPO });
      await tell(7, 'The comment.');
      assert.deepEqual(sent, [], JSON.stringify(row));
      assert.ok(logged.some((l) => l.event === TOLD && l.outcome === 'nobody told'));
    }
  });

  test('a read or a send that fails is logged at error, and never fails the turn', async () => {
    const read = logs();
    await specOwnerTeller({ read: async () => { throw new Error('HTTP 502'); }, relay: ['OWNER'], deliver: async () => delivered() as never, log: read.log, repo: REPO })(7, 'x');
    assert.ok(read.logged.some((l) => l.level === 'error' && /502/.test(String(l.error))));
    const send = logs();
    await specOwnerTeller({ read: async () => ({ body: `x\n\n${SPEC}`, association: 'OWNER' }), relay: ['OWNER'], deliver: async () => { throw new Error('boom'); }, log: send.log, repo: REPO })(7, 'x');
    assert.ok(send.logged.some((l) => l.level === 'error' && /boom/.test(String(l.error))));
    const failed = logs();
    await specOwnerTeller({ read: async () => ({ body: `x\n\n${SPEC}`, association: 'OWNER' }), relay: ['OWNER'], deliver: async () => delivered({ ok: false, error: 'HTTP 500' }) as never, log: failed.log, repo: REPO })(7, 'x');
    assert.ok(failed.logged.some((l) => l.level === 'error' && l.outcome === 'not messaged'));
  });

  test('a turn\'s tellers send one at a time, however many comments go side by side', async () => {
    // Each send is a CLI call on the one login, which may refresh it, so
    // two at once could spend a refresh token the other already rotated.
    let running = 0;
    let most = 0;
    const sent: number[] = [];
    const ctx = {
      readerFor: async () => ({ ticket: async () => ({ body: `x\n\n${SPEC}`, association: 'OWNER' }) }),
      configOf: () => ({ trust: { relay: ['OWNER'] } }),
      delivery: () => ({
        deliver: async (_to: unknown, _text: string, { on }: { on: number[] }) => {
          running += 1;
          most = Math.max(most, running);
          await new Promise((resolve) => setTimeout(resolve, 5));
          running -= 1;
          sent.push(on[0]!);
          return delivered();
        },
      }),
      log: logs().log,
    };
    await Promise.all([7, 8, 9].map((n) => tellerFor(ctx as never, REPO, 'github' as never)(n, 'x')));
    assert.deepEqual([...sent].sort(), [7, 8, 9]);
    assert.equal(most, 1);
  });
});

/** A reader whose ticket 7 has `thread`, and whose wait ticket is #9. */
const reader = ({ thread = [] as Array<{ body: string }>, linked = false, cap = false } = {}) => {
  const comments: Array<{ issue: number, body: string }> = [];
  return {
    comments,
    reader: {
      allComments: async () => [...thread, ...comments],
      comment: async (issue: number, body: string) => { comments.push({ issue, body }); },
      ticket: async (n: number) => ({ number: n, id: 900 + n, title: `Issue ${n}`, body: '', state: 'open', labels: [], pull: false }),
      blockers: async () => (linked ? [{ id: 909, number: 9, state: 'open' }] : []),
      blocking: async () => Array.from({ length: cap ? 50 : 0 }, (_, i) => ({ number: 100 + i, state: 'open' })),
      addBlocker: async () => { if (cap) throw Object.assign(new Error('POST failed: 422 at most 50'), { status: 422 }); },
      removeBlocker: async () => {},
      issue: async (n: number) => ({ number: n, body: '', pull: false }),
      issueClose: async (n: number) => ({ id: 900 + n, number: n, title: `Issue ${n}`, state: 'open', reason: null as string | null, closedAt: null as string | null }),
      updateIssue: async () => {},
    },
  };
};

describe('a wait warning tells the spec owner once, when it is posted', () => {
  test('an unreadable `Blocked until:` line', async () => {
    const { told, tell } = recorder();
    const f = reader();
    assert.equal(await reportUnreadable({ reader: f.reader, repo: REPO, issue: 7, value: 'soon', log: logs().log, tell }), 'commented');
    assert.deepEqual(told, [{ issue: 7, comment: f.comments[0]!.body }]);
    // Said already: nothing more is posted or told.
    assert.equal(await reportUnreadable({ reader: f.reader, repo: REPO, issue: 7, value: 'soon', log: logs().log, tell }), 'already told');
    assert.equal(told.length, 1);
  });

  test('a relative line governor cannot settle, and one on a close that was not completed', async () => {
    const { told, tell } = recorder();
    const f = reader();
    assert.equal(await repairRelative({ reader: f.reader as never, repo: REPO, issue: 7, after: { days: 3, issue: 143 }, link: false, prompts: {}, log: logs().log, tell }), 'commented');
    assert.ok(f.comments[0]!.body.includes(waitRelativeMarker('#143')));
    assert.deepEqual(told, [{ issue: 7, comment: f.comments[0]!.body }]);
    const closed = recorder();
    const g = reader();
    g.reader.issueClose = async (n: number) => ({ id: 900 + n, number: n, title: `Issue ${n}`, state: 'closed', reason: 'not_planned', closedAt: '2026-11-02T09:00:00Z' });
    assert.equal(await repairRelative({ reader: g.reader as never, repo: REPO, issue: 7, after: { days: 3, issue: 143 }, link: false, prompts: {}, log: logs().log, tell: closed.tell }), 'commented');
    assert.deepEqual(closed.told.map((t) => t.comment), [g.comments[0]!.body]);
  });

  test('a ticket linked to the wait ticket with no line', async () => {
    const { told, tell } = recorder();
    const f = reader({ linked: true });
    const links = waitLinks({ reader: f.reader as never, repo: REPO, board: 9, log: logs().log, tell });
    assert.equal(await links!.unlined(7), 'commented');
    assert.ok(f.comments[0]!.body.includes(WAIT_UNLINED_MARKER));
    assert.deepEqual(told, [{ issue: 7, comment: f.comments[0]!.body }]);
  });

  test('the wait ticket\'s full comment is for people, and tells nobody', async () => {
    const { told, tell } = recorder();
    const f = reader({ cap: true });
    const links = waitLinks({ reader: f.reader as never, repo: REPO, board: 9, log: logs().log, tell });
    assert.equal(await links!.show(7), 'wait ticket full');
    assert.ok(f.comments[0]!.body.includes(WAIT_FULL_MARKER));
    assert.deepEqual(told, []);
  });

});
