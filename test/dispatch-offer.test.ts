/**
 * The offer of an ownerless issue (#613, under PRD #599). A session's
 * signed comment on an issue nobody owns gets the commenter a message from
 * governor: nobody owns this issue, no owner reads your comments, and if
 * your comment changes what the issue asks, take it by editing its body so
 * your link ends it.
 *
 * An issue is ownerless where the session its owner link names refuses as
 * archived, learnt by sending it the comment (the spec owner's message on
 * an unclaimed issue, the ticket fire on a claimed one, both under
 * `subscribeMessages`), or where its body ends in the Claude Code footer
 * and names no session, a session's unsigned post (an `offer` fire, under
 * `sessionRules` alone). A person's issue, one `trust.relay` masks, a PR
 * and one of the ticket's builders get no offer.
 */

