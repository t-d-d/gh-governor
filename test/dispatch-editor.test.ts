type Sent = { session: string, text: string, opts: Record<string, unknown> };
const accepted = (session: string) => ({ ok: true, answered: true, refused: false, sessionUrl: session, error: null, fallback: null, dropped: null, skipped: null, relinked: null });
const faulted = () => ({ ok: false, answered: false, refused: false, sessionUrl: null, error: 'the CLI printed nothing', fallback: null, dropped: null, skipped: null, relinked: null });

describe('tellEditor', () => {
  const teller = (told = new Set<string>()) => {
    const sent: Sent[] = [];
    const logged: Array<Record<string, unknown>> = [];
    return {
      sent,
      logged,
      told,
      tellOnce: async (session: string, kind: string) => {
        const key = `${session.slice(session.lastIndexOf('/') + 1)}#${kind}`;
        if (told.has(key)) return false;
        told.add(key);
        return true;
      },
      deliveries: { deliver: async (to: { session?: string }, text: string, opts: Record<string, unknown>) => { sent.push({ session: String(to.session), text, opts }); return accepted(String(to.session)); } },
      log: (event: string, context: Record<string, unknown> = {}) => { logged.push({ event, ...context }); },
    };
  };

  test('the editor is told once to post its change as a comment, with the rules', async () => {
    const t = teller();
    const edited = { by: 'other' as const, found: { searched: true as const, author: WRITER, maybe: [], candidates: 2, unread: 0 } };
    await tellEditor({ repo: REPO, on: 7, edit: EDIT, edited, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    assert.deepEqual(t.sent.map((s) => [s.session, s.text]), [[WRITER, editNudgeText(7, ISSUE_URL)]]);
    assert.ok(t.told.has('session_01WRITER#edit-unsigned'));
    assert.match(t.sent[0]!.text, /as a comment/);
    assert.ok(t.sent[0]!.text.includes(SESSION_RULES));
    const again = teller(t.told);
    await tellEditor({ repo: REPO, on: 7, edit: EDIT, edited, tellOnce: again.tellOnce, deliveries: again.deliveries as never, log: again.log });
    assert.deepEqual(again.sent, []);
  });

  test('undecided: each candidate not ruled out is told the edit may be its own', async () => {
    const t = teller();
    await tellEditor({ repo: REPO, on: 7, edit: EDIT, edited: { by: 'other', found: { searched: true, author: null, maybe: [WRITER, OTHER], candidates: 2, unread: 0 } }, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    assert.deepEqual(t.sent.map((s) => [s.session, s.text]), [[WRITER, editMaybeText(7, ISSUE_URL)], [OTHER, editMaybeText(7, ISSUE_URL)]]);
    assert.ok(t.told.has('session_01OTHER#edit-unsigned-maybe'));
    assert.match(editMaybeText(7, ISSUE_URL), /may be yours/);
  });

  test('the owner\'s edit, all ruled out, an unread owner or no search: nobody is told', async () => {
    const t = teller();
    for (const edited of [
      { by: 'owner' as const },
      { by: 'unknown' as const, reason: 'x' },
      { by: 'other' as const, found: { searched: true as const, author: null, maybe: [], candidates: 1, unread: 0 } },
      { by: 'other' as const, found: { searched: false as const, reason: 'x' } },
    ]) await tellEditor({ repo: REPO, on: 7, edit: EDIT, edited, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    assert.deepEqual(t.sent, []);
  });

  test('with the asks off, nobody is told, whatever was found', async () => {
    const t = teller();
    for (const edited of [
      { by: 'other' as const, found: { searched: true as const, author: WRITER, maybe: [], candidates: 1, unread: 0 } },
      { by: 'other' as const, found: { searched: true as const, author: null, maybe: [WRITER, OTHER], candidates: 2, unread: 0 } },
    ]) assert.deepEqual(await tellEditor({ repo: REPO, on: 7, edit: EDIT, edited, asks: false, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log }), []);
    assert.deepEqual(t.sent, []);
    assert.deepEqual([...t.told], []);
    assert.ok(t.logged.every((l) => /sessionRules/.test(String(l.reason))), JSON.stringify(t.logged));
  });

  test('the texts use no em dash, and no event text is logged', async () => {
    assert.doesNotMatch(editNudgeText(7, ISSUE_URL), /—/);
    assert.doesNotMatch(editMaybeText(7, ISSUE_URL), /—/);
    const t = teller();
    const sessions = api([row('01OWNER'), row('01WRITER')], { cse_01OWNER: [], cse_01WRITER: [editCall(AT)] });
    const edited = await searchEditor({ owner: OWNER, list: sessions.list, events: sessions.events, repo: REPO, on: 7, edit: EDIT });
    await tellEditor({ repo: REPO, on: 7, edit: EDIT, edited, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    const line = JSON.stringify(t.logged).toLowerCase();
    assert.ok(t.logged.length > 0);
    for (const word of ['parser', 'trailing', 'newline', 'empty']) assert.ok(!line.includes(word), word);
  });
});

/** A TurnContext for planTicket, its editor search answering `edited`. */
const context = ({ edited = null as unknown, config = CONFIG, told = new Set<string>(), fails = [] as string[] } = {}) => {
  const sent: Sent[] = [];
  let searched = 0;
  const reader = {
    openClosing: async () => [],
    closure: async () => ({ pr: null }),
    allComments: async () => [{ body: `<!-- governor:dispatched ${new Date(AT - 60_000).toISOString()} -->\nDispatched to ${BUILDER} at ${new Date(AT - 60_000).toISOString()}.`, ours: true }],
  };
  const ctx = {
    readerFor: async () => reader,
    configOf: () => config,
    delivery: () => ({
      ownerOf: async () => ({ session: null }),
      deliver: async (to: { session?: string }, text: string, opts: Record<string, unknown>) => { sent.push({ session: String(to.session), text, opts }); return fails.includes(String(to.session)) ? faulted() : accepted(String(to.session)); },
    }),
    storeLogin: async () => false,
    state: {
      recordTold: async (session: string, kind: string) => {
        const key = `${session.slice(session.lastIndexOf('/') + 1)}#${kind}`;
        if (told.has(key)) return false;
        told.add(key);
        return true;
      },
    },
    now: () => LATE,
    log: () => {},
    findAuthor: async () => { throw new Error('no post is searched here'); },
    findEditor: async (_on: number, _edit: unknown, owner: string) => { searched += 1; assert.equal(owner, OWNER); return edited; },
  };
  return { ctx: ctx as never, sent, searched: () => searched };
};

const TEXT = `The body of issue #7 was edited.\n\nIssue #7: The parser (${ISSUE_URL}), edited by t-d-d`;
const fire = (over: Record<string, unknown> = {}) => ({ kind: 'ticket', repo: REPO, issue: 7, text: TEXT, event: 'edit', state: 'open', labels: [CLAIM], owner: OWNER, authors: ['OWNER'], edited: EDIT, ...over }) as never;
const ownerOf = (sent: Sent[]) => sent.find((s) => s.session === OWNER);

describe('planTicket: a body edit that leaves the owner link in place', () => {
  test('an owner whose own events show the edit is not told of it; the builder still is', async () => {
    const { ctx, sent } = context({ edited: { by: 'owner' } });
    const plan = await planTicket(fire(), ctx) as any;
    assert.deepEqual(sent.map((s) => s.session), [BUILDER]);
    assert.ok(sent[0]!.text.includes(EDIT_BUILDER));
    assert.equal(exitCodeFor(plan.answer), 0);
  });

  test('an unclaimed ticket\'s owner that made the edit hears nothing', async () => {
    const { ctx, sent } = context({ edited: { by: 'owner' } });
    await planTicket(fire({ labels: ['mode: afk'] }), ctx);
    assert.deepEqual(sent, []);
  });

  test('another candidate made it: it is nudged once, and the owner told another session edited its issue', async () => {
    const told = new Set<string>();
    const edited = { by: 'other', found: { searched: true, author: WRITER, maybe: [], candidates: 2, unread: 0 } };
    const first = context({ edited, told });
    await planTicket(fire(), first.ctx);
    assert.deepEqual(first.sent.map((s) => s.session), [OWNER, BUILDER, WRITER]);
    assert.match(ownerOf(first.sent)!.text, /another session/i);
    assert.doesNotMatch(ownerOf(first.sent)!.text, /may be your own/);
    assert.equal(first.sent[2]!.text, editNudgeText(7, ISSUE_URL));
    const second = context({ edited, told });
    await planTicket(fire(), second.ctx);
    assert.deepEqual(second.sent.map((s) => s.session), [OWNER, BUILDER]);
  });

  test('undecided: the candidates are told it may be theirs, and the owner that someone else edited it', async () => {
    const { ctx, sent } = context({ edited: { by: 'other', found: { searched: true, author: null, maybe: [WRITER, OTHER], candidates: 2, unread: 0 } } });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER, WRITER, OTHER]);
    assert.match(ownerOf(sent)!.text, /someone else/i);
    assert.doesNotMatch(ownerOf(sent)!.text, /may be your own/);
    assert.equal(sent[3]!.text, editMaybeText(7, ISSUE_URL));
  });

  test('all ruled out: the owner is told someone else edited it, most likely a person, and nobody is nudged', async () => {
    const { ctx, sent } = context({ edited: { by: 'other', found: { searched: true, author: null, maybe: [], candidates: 2, unread: 0 } } });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER]);
    assert.match(ownerOf(sent)!.text, /most likely a person/i);
  });

  test('the owner\'s events cannot be read: the owner gets today\'s notice', async () => {
    const { ctx, sent } = context({ edited: { by: 'unknown', reason: 'the events read failed' } });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER]);
    assert.ok(ownerOf(sent)!.text.includes(EDIT_SPEC_OWNER));
  });

  test('the builder hears every edit, the same words as before', async () => {
    for (const edited of [{ by: 'owner' }, { by: 'unknown', reason: 'x' }, { by: 'other', found: { searched: true, author: BUILDER, maybe: [], candidates: 1, unread: 0 } }]) {
      const { ctx, sent } = context({ edited });
      await planTicket(fire(), ctx);
      const builder = sent.filter((s) => s.session === BUILDER);
      assert.ok(builder.some((s) => s.text.includes(EDIT_BUILDER)), JSON.stringify(edited));
    }
  });

  test('a spec owner that is also the builder and made the edit hears only the builder\'s line', async () => {
    const { ctx, sent } = context({ edited: { by: 'owner' } });
    // The builder lookup finds OWNER as the builder too.
    (ctx as any).readerFor = async () => ({
      openClosing: async () => [],
      closure: async () => ({ pr: null }),
      allComments: async () => [{ body: `<!-- governor:dispatched ${new Date(AT - 60_000).toISOString()} -->\nDispatched to ${OWNER} at ${new Date(AT - 60_000).toISOString()}.`, ours: true }],
    });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER]);
    assert.ok(sent[0]!.text.includes(EDIT_BUILDER));
    assert.ok(!sent[0]!.text.includes(EDIT_SPEC_OWNER));
  });

  test('with sessionRules off, an owner whose own events show the edit is still not told of it', async () => {
    const { ctx, sent, searched } = context({ config: RULES_OFF, edited: { by: 'owner' } });
    await planTicket(fire(), ctx);
    assert.equal(searched(), 1);
    assert.deepEqual(sent.map((s) => s.session), [BUILDER]);
    const unclaimed = context({ config: RULES_OFF, edited: { by: 'owner' } });
    await planTicket(fire({ labels: ['mode: afk'] }), unclaimed.ctx);
    assert.deepEqual(unclaimed.sent, []);
  });

  test('with sessionRules off, another session\'s edit is told to the owner, and nobody is asked to comment instead', async () => {
    const told = new Set<string>();
    const { ctx, sent } = context({ config: RULES_OFF, told, edited: { by: 'other', found: { searched: true, author: WRITER, maybe: [], candidates: 2, unread: 0 } } });
    const plan = await planTicket(fire(), ctx) as any;
    assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER]);
    assert.match(ownerOf(sent)!.text, /another session made the edit/i);
    assert.doesNotMatch(ownerOf(sent)!.text, /may be your own|governor tells it/i);
    assert.deepEqual([...told], []);
    assert.equal(exitCodeFor(plan.answer), 0);
  });

  test('with sessionRules off, undecided candidates are not told the edit may be theirs', async () => {
    const { ctx, sent } = context({ config: RULES_OFF, edited: { by: 'other', found: { searched: true, author: null, maybe: [WRITER, OTHER], candidates: 2, unread: 0 } } });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER]);
    assert.match(ownerOf(sent)!.text, /someone else/i);
  });

  test('with sessionRules off, an owner whose events cannot be read gets today\'s notice', async () => {
    const { ctx, sent } = context({ config: RULES_OFF, edited: { by: 'unknown', reason: 'the events read failed' } });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER]);
    assert.ok(ownerOf(sent)!.text.includes(EDIT_SPEC_OWNER));
  });

  test('a nudge that faults fails the turn', async () => {
    const { ctx } = context({ edited: { by: 'other', found: { searched: true, author: WRITER, maybe: [], candidates: 1, unread: 0 } }, fails: [WRITER] });
    const plan = await planTicket(fire(), ctx) as any;
    assert.equal(exitCodeFor(plan.answer), 1);
  });
});
