/**
 * A take confirmed, or a live owner's link written back (#614, under PRD
 * #599). An `issues` `edited` delivery, sent by no bot, whose old body
 * names owner A, or no session, and whose new body names B, where B is not
 * A, moved the issue's owner link. With `sessionRules` and
 * `subscribeMessages` on:
 *
 * - the edit's notice goes to A, and B is not sent its own edit;
 * - where A refuses as archived, or the old body was a session's unsigned
 *   post, B is told it owns the issue: a take, not a correction;
 * - where A takes the notice, governor writes A's link back where the body
 *   still names B, keeps the rest of B's edit, and tells B once;
 * - where B builds the ticket, or the old body was a person's, there is no
 *   take: A's link is written back, or B's removed, and B is told once.
 *
 * With either switch off, a body edit reaches the roles as today.
 */

