describe('takeText and correctionText', () => {
  test('a take tells the session it owns the issue, and why', () => {
    assert.match(takeText(7, 'archived'), /You now own #7/);
    assert.match(takeText(7, 'archived'), /archived/);
    assert.match(takeText(7, 'unsigned'), /without signing/);
    assert.doesNotMatch(takeText(7, 'unsigned'), /—/);
  });

  test('each correction says what happened, to comment next time, and carries the rules', () => {
    const owned = correctionText(7, 'edit-owned', OWNER);
    assert.match(owned, /does not own|you do not own/);
    assert.match(owned, /link was replaced by the owner's|put the owner's link back/);
    assert.match(correctionText(7, 'edit-builder', OWNER), /builder does not edit/);
    assert.match(correctionText(7, 'edit-builder', null), /removed your link/);
    assert.match(correctionText(7, 'edit-person', null), /person/);
    for (const text of [owned, correctionText(7, 'edit-builder', null), correctionText(7, 'edit-person', null)]) {
      assert.match(text, /comment/);
      assert.ok(text.includes(SESSION_RULES));
      assert.doesNotMatch(text, /—/);
    }
  });
});

type Sent = { session: string, text: string, opts: Record<string, unknown> };
type Delivery = { ok: boolean, answered: boolean | null, refused: boolean, capped?: boolean, sessionUrl: string | null, error: string | null, fallback: null, dropped: boolean | null, skipped: null, relinked: null };

const MARKER = dispatchMarker({ at: new Date(NOW - 60_000).toISOString(), sessionUrl: BUILDER });

/**
 * A `TurnContext` whose reader holds issue 7 with `body` (as it reads now),
 * its thread `comments`; `archived` the sessions that refuse, `capped`
 * those the ceiling holds back, `fails` those whose send faults.
 */
const context = ({
  body = TAKEN, comments = [{ body: MARKER }] as Array<{ body: string }>, archived = [] as string[], capped = [] as string[], fails = [] as string[],
  config = CONFIG, readFails = false, writeFails = false, told = new Set<string>(),
} = {}) => {
  const sent: Sent[] = [];
  const writes: Array<{ issue: number, body: string }> = [];
  const logged: Array<Record<string, unknown>> = [];
  const reader = {
    ticket: async (n: number) => {
      if (readFails) throw new Error('GitHub answered 502');
      return { number: n, title: 'A ticket', body, state: 'open', labels: [], pull: false, author: 't-d-d', association: 'OWNER' };
    },
    updateIssue: async (n: number, change: { body: string }) => {
      if (writeFails) throw new Error('GitHub answered 403');
      writes.push({ issue: n, body: change.body });
    },
    openClosing: async () => [],
    closure: async () => ({ pr: null }),
    allComments: async () => comments.map((c) => ({ ...c, ours: true })),
  };
  const answer = (session: string): Delivery => {
    if (fails.includes(session)) return { ok: false, answered: false, refused: false, sessionUrl: null, error: 'the CLI printed nothing', fallback: null, dropped: null, skipped: null, relinked: null };
    if (capped.includes(session)) return { ok: false, answered: null, refused: false, capped: true, sessionUrl: null, error: 'held at the message ceiling', fallback: null, dropped: null, skipped: null, relinked: null };
    const gone = archived.includes(session);
    return { ok: !gone, answered: true, refused: gone, sessionUrl: session, error: gone ? `cloud session ${session} is archived and cannot accept new messages` : null, fallback: null, dropped: gone ? true : null, skipped: null, relinked: null };
  };
  const ctx = {
    readerFor: async () => reader,
    configOf: () => config,
    served: [],
    bare: false,
    prompts: config.prompts,
    delivery: () => ({
      ownerOf: async () => ({ session: null }),
      deliver: async ({ session }: { session: string }, text: string, opts: Record<string, unknown>) => {
        sent.push({ session, text, opts });
        return answer(session);
      },
    }),
    storeLogin: async () => false,
    state: {
      recordTold: async (session: string, kind: string) => {
        const key = `${session.slice(session.lastIndexOf('/') + 1)}#${kind}`;
        if (told.has(key)) return false;
        told.add(key);
        return true;
      },
    },
    start: async () => { throw new Error('a body edit starts nothing'); },
    open: async () => true,
    claims: new Set<string>(),
    beats: [],
    now: () => NOW,
    log: (event: string, context: Record<string, unknown> = {}) => { logged.push({ event, ...context }); },
    sleep: async () => {},
    cap: 2,
  };
  return { ctx: ctx as never, sent, writes, logged, told };
};

const TEXT = 'The body of issue #7 was edited.\n\nIssue #7: A ticket (https://github.com/acme/factory/issues/7), edited by t-d-d';
const editFire = (over: Record<string, unknown> = {}) => ({ kind: 'ticket', repo: REPO, issue: 7, text: TEXT, event: 'edit', state: 'open', labels: [CLAIM], owner: EDITOR, authors: ['OWNER'], moved: { old: 'owned', from: OWNER }, ...over }) as never;
const to = (sent: Sent[]) => sent.map((s) => s.session);

describe('planTicket: a body edit that moved the owner link, under sessionRules', () => {
  test('the notice goes to the old owner and the builder, not to the editor', async () => {
    const { ctx, sent } = context();
    await planTicket(editFire(), ctx);
    assert.deepEqual(to(sent).slice(0, 2), [OWNER, BUILDER]);
    assert.ok(!sent.slice(0, 2).some((s) => s.session === EDITOR));
    assert.match(sent[0]!.text, /body of issue #7 was edited/);
  });

  test('a live owner keeps its issue: its link is written back, the rest of the edit stays, and the editor is told once', async () => {
    const { ctx, sent, writes, told } = context();
    const plan = await planTicket(editFire(), ctx) as any;
    assert.equal(writes.length, 1);
    assert.equal(sessionNamedIn(writes[0]!.body), OWNER);
    assert.match(writes[0]!.body, /with the empty case/);
    const correction = sent.filter((s) => s.session === EDITOR);
    assert.equal(correction.length, 1);
    assert.equal(correction[0]!.text, correctionText(7, 'edit-owned', OWNER));
    assert.deepEqual(correction[0]!.opts.on, [7]);
    assert.equal(exitCodeFor(plan.answer), 0);
    // A second such edit: the link is written back again, and the editor told nothing.
    const again = context({ told });
    await planTicket(editFire(), again.ctx);
    assert.equal(again.writes.length, 1);
    assert.deepEqual(again.sent.filter((s) => s.session === EDITOR), []);
  });

  test('an archived old owner, or an unsigned old body, is a take: the editor is told it owns the issue, and nothing is written', async () => {
    const gone = context({ archived: [OWNER] });
    await planTicket(editFire(), gone.ctx);
    assert.deepEqual(gone.writes, []);
    assert.deepEqual(gone.sent.filter((s) => s.session === EDITOR).map((s) => s.text), [takeText(7, 'archived')]);
    const unsigned = context();
    await planTicket(editFire({ moved: { old: 'unsigned' } }), unsigned.ctx);
    assert.deepEqual(unsigned.writes, []);
    assert.deepEqual(to(unsigned.sent), [BUILDER, EDITOR]);
    assert.equal(unsigned.sent[1]!.text, takeText(7, 'unsigned'));
  });

  test('a take is no correction: a second take is confirmed again', async () => {
    const told = new Set<string>();
    for (let i = 0; i < 2; i += 1) {
      const { ctx, sent } = context({ archived: [OWNER], told });
      await planTicket(editFire(), ctx);
      assert.equal(sent.filter((s) => s.session === EDITOR).length, 1);
    }
  });

  test('a builder\'s edit is no take: the old owner\'s link is written back, or the builder\'s removed, and it is told once', async () => {
    const live = context({ body: `The spec, changed.\n\n${BUILDER}${FOOTER}` });
    await planTicket(editFire({ owner: BUILDER }), live.ctx);
    assert.equal(sessionNamedIn(live.writes[0]!.body), OWNER);
    assert.deepEqual(live.sent.map((s) => [s.session, s.text === correctionText(7, 'edit-builder', OWNER)]), [[OWNER, false], [BUILDER, true]]);
    const gone = context({ body: `The spec, changed.\n\n${BUILDER}${FOOTER}`, archived: [OWNER] });
    await planTicket(editFire({ owner: BUILDER }), gone.ctx);
    assert.equal(sessionNamedIn(gone.writes[0]!.body), OWNER, 'a builder never takes the spec, even from an archived owner');
    const unsigned = context({ body: `The spec, changed.\n\n${BUILDER}${FOOTER}` });
    await planTicket(editFire({ owner: BUILDER, moved: { old: 'unsigned' } }), unsigned.ctx);
    assert.equal(sessionNamedIn(unsigned.writes[0]!.body), null, 'no old owner: the builder\'s link is removed');
    assert.equal(unsigned.sent.at(-1)!.text, correctionText(7, 'edit-builder', null));
  });

  test('an edit to a person\'s issue is no take: the editor\'s link is removed, and it is told once', async () => {
    const { ctx, sent, writes } = context({ body: `A person's spec, changed.\n\n${EDITOR}` });
    await planTicket(editFire({ labels: ['mode: afk'], moved: { old: 'person' } }), ctx);
    assert.deepEqual(writes, [{ issue: 7, body: 'A person\'s spec, changed.' }]);
    assert.deepEqual(sent.map((s) => [s.session, s.text]), [[EDITOR, correctionText(7, 'edit-person', null)]]);
  });

  test('an edit that signed a person\'s issue with a footer and a link loses both, so the issue stays the person\'s and is no session\'s unsigned post', async () => {
    for (const editor of [EDITOR, BUILDER]) {
      const { ctx, writes } = context({ body: `A person's spec, changed.\n\n${editor}${FOOTER}` });
      await planTicket(editFire({ owner: editor, moved: { old: 'person' } }), ctx);
      assert.deepEqual(writes, [{ issue: 7, body: 'A person\'s spec, changed.' }], editor);
      assert.equal(unsignedSessionBody(writes[0]!.body), false, editor);
    }
  });

  // #622: the write-back finds the editor's link by the rule sessionNamedIn reads it.
  test('an editor\'s link governor reads above the PR-style footer, however written, is the one written back or removed', async () => {
    const PR_FOOTER = '\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)';
    for (const written of [EDITOR, `Session: <${EDITOR}>.`, `_[this session](${EDITOR})_`]) {
      const body = `The spec, with the empty case.\n\n${written}${PR_FOOTER}`;
      assert.equal(sessionNamedIn(body), EDITOR, written);
      const live = context({ body });
      await planTicket(editFire(), live.ctx);
      assert.equal(live.writes.length, 1, written);
      assert.equal(sessionNamedIn(live.writes[0]!.body), OWNER, written);
      assert.ok(!live.writes[0]!.body.includes(EDITOR), written);
      const person = context({ body: `A person's spec, changed.\n\n${written}${PR_FOOTER}` });
      await planTicket(editFire({ moved: { old: 'person' } }), person.ctx);
      assert.deepEqual(person.writes, [{ issue: 7, body: 'A person\'s spec, changed.' }], written);
    }
  });

  test('where the body no longer names the editor, or the read or the write fails, nothing is written and the editor is told nothing', async () => {
    const cases: Array<[string, Parameters<typeof context>[0]]> = [
      ['moved on', { body: `The spec, again.\n\n${BUILDER}${FOOTER}` }],
      ['read fails', { readFails: true }],
      ['write fails', { writeFails: true }],
    ];
    for (const [name, over] of cases) {
      const { ctx, sent, writes, logged } = context(over);
      const plan = await planTicket(editFire(), ctx) as any;
      assert.deepEqual(writes, [], name);
      assert.deepEqual(sent.filter((s) => s.session === EDITOR), [], name);
      assert.equal(exitCodeFor(plan.answer), 0, name);
      if (name !== 'moved on') assert.ok(logged.some((l) => l.event === 'dispatch-spec-owner' && l.level === 'error'), name);
    }
  });

  test('a notice the ceiling holds back changes nothing else; one that faults fails the turn and changes nothing else', async () => {
    const held = context({ capped: [OWNER] });
    await planTicket(editFire({ labels: ['mode: afk'] }), held.ctx);
    assert.deepEqual([held.writes, to(held.sent)], [[], [OWNER]]);
    const faulted = context({ fails: [OWNER] });
    const plan = await planTicket(editFire({ labels: ['mode: afk'] }), faulted.ctx) as any;
    assert.deepEqual([faulted.writes, to(faulted.sent)], [[], [OWNER]]);
    assert.equal(exitCodeFor(plan.answer), 1);
  });

  test('a correction that faults fails the turn', async () => {
    const { ctx } = context({ fails: [EDITOR] });
    const plan = await planTicket(editFire({ labels: ['mode: afk'] }), ctx) as any;
    assert.equal(exitCodeFor(plan.answer), 1);
  });

  test('with sessionRules off, the edit reaches the roles as today: the new owner, told it may be its own, and the builder', async () => {
    const { ctx, sent, writes } = context({ config: RULES_OFF });
    await planTicket(editFire(), ctx);
    assert.deepEqual(to(sent), [EDITOR, BUILDER]);
    assert.match(sent[0]!.text, /may be your own/);
    assert.deepEqual(writes, []);
  });
});
