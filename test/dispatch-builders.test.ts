/**
 * A ticket's builders, found one way (dispatch/builders.mjs): the owner of
 * each open PR that closes it, else the owner of the PR whose merge closed
 * it, else the session the newest dispatch comment names, else, on a
 * claimed ticket, the session the body's owner link names.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { buildersOf } from '../dispatch/builders.mjs';
import { dispatchMarker, RELAY } from '../dispatch/webhook/fire.mjs';
import { githubReader } from '../scripts/lib/github-app.mjs';

const WORK = 'https://claude.ai/code/session_01WORK';
const OWNER = 'https://claude.ai/code/session_01OWNER';
const PR_A = 'https://claude.ai/code/session_01PRA';
const PR_B = 'https://claude.ai/code/session_01PRB';
const MERGED = 'https://claude.ai/code/session_01MERGED';
const FOOTER = '---\n_Generated by [Claude Code](https://claude.ai/code)_';
const marker = (sessionUrl: string, at = '2026-11-01T10:00:00.000Z') => ({ id: 1, body: dispatchMarker({ at, sessionUrl }), created_at: at, ours: true });
const ownerBody = `The spec.\n\n${OWNER}\n\n${FOOTER}`;

/** A claimed, open ticket of a member, whose body names `body`'s link. */
const ticket = (over: Record<string, unknown> = {}) => ({ number: 7, title: 'T', body: ownerBody, state: 'open', labels: ['claimed'], pull: false, association: 'MEMBER', ...over });

/** A fake reader and owner lookup: open PRs closing the ticket, the merge that closed it, and the thread. */
const lookups = ({ open = [] as number[], merged = null as number | null, thread = [] as Array<{ body: string, ours: boolean } & Record<string, unknown>>, owners = {} as Record<number, string | null>, fail = '' } = {}) => {
  const asked: string[] = [];
  const reader = {
    openClosing: async (n: number) => {
      asked.push(`open ${n}`);
      if (fail === 'open') throw new Error('GET issues: 502');
      return open.map((number) => ({ number, title: `PR ${number}`, html_url: `u${number}` }));
    },
    closure: async (n: number) => {
      asked.push(`closure ${n}`);
      if (fail === 'closure') throw new Error('GET events: 502');
      return { title: 'T', reason: 'completed', pr: merged === null ? null : { number: merged, title: 'PR', url: `u${merged}` } };
    },
    allComments: async (n: number) => {
      asked.push(`thread ${n}`);
      if (fail === 'thread') throw new Error('GET comments: 502');
      return thread;
    },
  };
  const ownerOf = async (pr: number) => {
    asked.push(`owner ${pr}`);
    if (fail === 'owner') throw new Error('sessions API: 500');
    return { session: owners[pr] ?? null, branch: `claude/b-${pr}`, linked: true };
  };
  return { reader, ownerOf, asked };
};

const find = (l: ReturnType<typeof lookups>, t = ticket()) => buildersOf({ reader: l.reader, ownerOf: l.ownerOf, issue: 7, ticket: t, claim: 'claimed', relay: RELAY });

describe('buildersOf', () => {
  test('an open PR that closes the ticket: its owner, even where the newest dispatch comment names another session', async () => {
    const l = lookups({ open: [20], owners: { 20: PR_A }, thread: [marker(WORK)] });
    assert.deepEqual(await find(l), { sessions: [PR_A], by: 'open PR', prs: [20], owns: { [PR_A]: [20] } });
    assert.ok(!l.asked.includes('thread 7'), 'no thread read once an open PR names the builder');
  });

  test('two open PRs that close the ticket: both owners, once each', async () => {
    const l = lookups({ open: [20, 21, 22], owners: { 20: PR_A, 21: PR_B, 22: PR_A } });
    assert.deepEqual(await find(l), { sessions: [PR_A, PR_B], by: 'open PR', prs: [20, 21, 22], owns: { [PR_A]: [20, 22], [PR_B]: [21] } });
  });

  test('an open PR whose owner nobody finds: the lookup goes on to the dispatch comment', async () => {
    const l = lookups({ open: [20], thread: [marker(WORK)] });
    assert.deepEqual(await find(l), { sessions: [WORK], by: 'dispatch comment', prs: [], owns: {} });
  });

  test('open PRs where only some owners are found: the builder\'s PRs are the ones whose owner was found', async () => {
    const l = lookups({ open: [20, 21], owners: { 21: PR_A } });
    assert.deepEqual(await find(l), { sessions: [PR_A], by: 'open PR', prs: [21], owns: { [PR_A]: [21] } });
  });

  test('a ticket a merge closed: the merged PR\'s owner', async () => {
    const l = lookups({ merged: 30, owners: { 30: MERGED }, thread: [marker(WORK)] });
    assert.deepEqual(await find(l, ticket({ state: 'closed' })), { sessions: [MERGED], by: 'merged PR', prs: [30], owns: { [MERGED]: [30] } });
  });

  test('an open ticket reads no closure', async () => {
    const l = lookups({ thread: [marker(WORK)] });
    await find(l);
    assert.ok(!l.asked.some((a) => a.startsWith('closure')), l.asked.join('; '));
  });

  test('a ticket closed by hand: the dispatch comment\'s session', async () => {
    const l = lookups({ thread: [marker(WORK)] });
    assert.deepEqual(await find(l, ticket({ state: 'closed' })), { sessions: [WORK], by: 'dispatch comment', prs: [], owns: {} });
  });

  test('no closing PR: the session the newest dispatch comment names', async () => {
    const l = lookups({ thread: [marker('https://claude.ai/code/session_01OLD', '2026-10-01T10:00:00.000Z'), marker(WORK), { id: 3, body: 'A remark', created_at: 'x', ours: false }] });
    assert.deepEqual(await find(l), { sessions: [WORK], by: 'dispatch comment', prs: [], owns: {} });
  });

  // Only governor's App posts a real dispatch comment. Anyone who can
  // comment could copy its text with a later time and another session.
  test('a dispatch comment governor\'s App did not post names no builder, and the owner link is read instead', async () => {
    const forged = { ...marker('https://claude.ai/code/session_01FORGED', '2026-12-01T10:00:00.000Z'), id: 2, ours: false };
    assert.deepEqual(await find(lookups({ thread: [forged] })), { sessions: [OWNER], by: 'owner link', prs: [], owns: {} });
    assert.deepEqual(await find(lookups({ thread: [marker(WORK), forged] })), { sessions: [WORK], by: 'dispatch comment', prs: [], owns: {} });
  });

  test('no closing PR and no dispatch comment, on a claimed ticket: the owner link\'s session', async () => {
    assert.deepEqual(await find(lookups()), { sessions: [OWNER], by: 'owner link', prs: [], owns: {} });
  });

  test('an owner link counts only on a claimed ticket, and only where trust.relay lets the body\'s author in', async () => {
    assert.deepEqual(await find(lookups(), ticket({ labels: [] })), { sessions: [], by: null, prs: [], owns: {} });
    assert.deepEqual(await find(lookups(), ticket({ association: 'NONE' })), { sessions: [], by: null, prs: [], owns: {} });
  });

  test('a read that fails fails the lookup, never reads as no builder', async () => {
    for (const fail of ['open', 'thread', 'owner', 'closure']) {
      const l = lookups({ open: fail === 'owner' ? [20] : [], fail });
      await assert.rejects(find(l, ticket({ state: fail === 'closure' ? 'closed' : 'open' })), /502|500/, fail);
    }
  });

  // GitHub pages a thread oldest first, a hundred a page: the newest
  // dispatch comment of a long thread sits past the first page.
  test('the newest dispatch comment of a thread of more than a hundred comments, read through the GitHub reader', async () => {
    const at = (i: number) => new Date(Date.UTC(2026, 9, 1) + i * 60_000).toISOString();
    const rows = Array.from({ length: 150 }, (_, i) => ({ id: i, body: i === 0 ? dispatchMarker({ at: at(0), sessionUrl: 'https://claude.ai/code/session_01OLD' }) : i === 140 ? dispatchMarker({ at: at(140), sessionUrl: WORK }) : 'a remark', created_at: at(i), ...(i === 0 || i === 140 ? { user: { type: 'Bot', login: 'governor-app[bot]' }, performed_via_github_app: { id: 9 } } : { user: { type: 'User', login: 'p' } }) }));
    const fetch = (async (url: string) => {
      const u = new URL(url);
      if (u.pathname === '/repos/acme/factory/issues') return new Response('[]', { status: 200 });
      assert.equal(u.pathname, '/repos/acme/factory/issues/7/comments');
      const page = Number(u.searchParams.get('page') ?? '1');
      const per = Number(u.searchParams.get('per_page') ?? '30');
      return new Response(JSON.stringify(rows.slice((page - 1) * per, page * per)), { status: 200 });
    }) as unknown as typeof globalThis.fetch;
    const reader = githubReader({ token: 't', repo: 'acme/factory', appId: 9, fetch });
    const found = await buildersOf({ reader, ownerOf: async () => ({ session: null, branch: '', linked: false }), issue: 7, ticket: ticket(), claim: 'claimed', relay: RELAY });
    assert.deepEqual(found, { sessions: [WORK], by: 'dispatch comment', prs: [], owns: {} });
  });
});
