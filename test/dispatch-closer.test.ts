/**
 * A session is not told of a close it made itself (#689). Every session
 * acts as the operator's login, so a close's delivery names only that
 * login. As for a body edit (dispatch/editor.mjs), governor reads the
 * session's own events around the close's time, from the payload, for a
 * call that closed the issue or PR, before it tells the session:
 *
 * - found: the session closed it, and is not told of its own close;
 * - not found: it hears the close as before;
 * - its events cannot be read: it hears the close as before.
 *
 * Nobody else's message changes, and nobody is nudged.
 */

