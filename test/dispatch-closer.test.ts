/** A tool call event at `when` (ms). */
const call = (when: number, name: string, input: Record<string, unknown>, id = `e-${when}-${name}`) => ({
  event_id: id,
  event_type: 'assistant',
  created_at: new Date(when).toISOString(),
  payload: { type: 'assistant', message: { content: [{ type: 'tool_use', id: `t-${id}`, name, input }] } },
});
const closeCall = (when: number) => call(when, 'Bash', { command: 'gh issue close 7 --reason completed' });
const commentCall = (when: number) => call(when, 'mcp__github__add_issue_comment', { owner: 'acme', repo: 'factory', issue_number: 7, body: 'Done.' });

/** A sessions API: each session's events newest first in one page, unless `fails` names it. */
const api = (events: Record<string, unknown[]>, { fails = [] as string[] } = {}) => {
  const read: string[] = [];
  return {
    read,
    events: async (id: string) => {
      read.push(id);
      if (fails.includes(id)) throw new Error('GET events: 502');
      return { data: [...(events[id] ?? [])].sort((a: any, b: any) => Date.parse(b.created_at) - Date.parse(a.created_at)), next_cursor: null };
    },
  };
};

describe('searchCloser', () => {
  const search = (sessions: ReturnType<typeof api>, session = OWNER) => searchCloser({ session, events: sessions.events, repo: REPO, on: 7, at: CLOSED_AT });

  test('the session\'s own events show the close: it closed it, and only its events are read', async () => {
    const sessions = api({ cse_01OWNER: [commentCall(AT - 5000), closeCall(AT - 2000)] });
    assert.deepEqual(await search(sessions), { by: 'self' });
    assert.deepEqual(sessions.read, ['cse_01OWNER']);
  });

  test('the window is the close\'s: a call outside it is not the session\'s close', async () => {
    const sessions = api({ cse_01OWNER: [closeCall(AT - AUTHOR_BEFORE_MS - 1000), closeCall(AT + AUTHOR_AFTER_MS + 1000)] });
    assert.deepEqual(await search(sessions), { by: 'other' });
  });

  test('no close among its events: someone else closed it', async () => {
    assert.deepEqual(await search(api({ cse_01OWNER: [commentCall(AT)] })), { by: 'other' });
  });

  test('its events cannot be read: unknown, with a reason', async () => {
    const found = await search(api({}, { fails: ['cse_01OWNER'] }));
    assert.equal(found.by, 'unknown');
    assert.match((found as { reason: string }).reason, /events read failed/);
  });
});

type Sent = { session: string, text: string };
const accepted = (session: string) => ({ ok: true, answered: true, refused: false, sessionUrl: session, error: null, fallback: null, dropped: null, skipped: null, relinked: null });

/** A TurnContext for planTicket, its close search answering from `closers`. */
const context = ({ closers = {} as Record<string, unknown>, builder = BUILDER } = {}) => {
  const sent: Sent[] = [];
  const searched: string[] = [];
  const reader = {
    openClosing: async () => [],
    closure: async () => ({ pr: null }),
    allComments: async () => [{ body: `<!-- governor:dispatched ${new Date(AT - 60_000).toISOString()} -->\nDispatched to ${builder} at ${new Date(AT - 60_000).toISOString()}.`, ours: true }],
  };
  const ctx = {
    readerFor: async () => reader,
    configOf: () => CONFIG,
    delivery: () => ({
      ownerOf: async () => ({ session: null }),
      deliver: async (to: { session?: string }, text: string) => { sent.push({ session: String(to.session), text }); return accepted(String(to.session)); },
    }),
    storeLogin: async () => false,
    state: { recordTold: async () => true },
    now: () => AT + 60_000,
    log: () => {},
    findAuthor: async () => { throw new Error('no post is searched here'); },
    findEditor: async () => { throw new Error('no edit is searched here'); },
    findCloser: async (on: number, at: string, session: string) => {
      assert.equal(on, 7);
      assert.equal(at, CLOSED_AT);
      searched.push(session);
      return closers[session] ?? { by: 'other' };
    },
  };
  return { ctx: ctx as never, sent, searched };
};

const TEXT = `Issue #7: The parser (${ISSUE_URL}) was closed (completed) by t-d-d.`;
const fire = (over: Record<string, unknown> = {}) => ({ kind: 'ticket', repo: REPO, issue: 7, text: TEXT, event: 'close', state: 'closed', labels: [CLAIM], owner: OWNER, closing: true, authors: ['OWNER'], closedAt: CLOSED_AT, ...over }) as never;

describe('planTicket: a close a role made itself', () => {
  test('the spec owner that closed the ticket is not told of it; the builder still is', async () => {
    const { ctx, sent } = context({ closers: { [OWNER]: { by: 'self' } } });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [BUILDER]);
  });

  test('the builder that closed the ticket is not told of it; the spec owner still is', async () => {
    const { ctx, sent } = context({ closers: { [BUILDER]: { by: 'self' } } });
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER]);
  });

  test('an unclaimed ticket\'s owner that closed it hears nothing', async () => {
    const { ctx, sent } = context({ closers: { [OWNER]: { by: 'self' } } });
    await planTicket(fire({ labels: ['mode: afk'] }), ctx);
    assert.deepEqual(sent, []);
  });

  test('someone else closed it, or a role\'s events cannot be read: every role hears it as before', async () => {
    for (const found of [{ by: 'other' }, { by: 'unknown', reason: 'the events read failed' }]) {
      const { ctx, sent } = context({ closers: { [OWNER]: found, [BUILDER]: found } });
      await planTicket(fire(), ctx);
      assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER], JSON.stringify(found));
      assert.ok(sent.every((s) => s.text.startsWith(TEXT)));
    }
  });

  test('a fire with no close time searches nothing, and every role hears it', async () => {
    const { ctx, sent, searched } = context({ closers: { [OWNER]: { by: 'self' } } });
    await planTicket(fire({ closedAt: undefined }), ctx);
    assert.deepEqual(searched, []);
    assert.deepEqual(sent.map((s) => s.session), [OWNER, BUILDER]);
  });

  test('a reopen searches nothing', async () => {
    const { ctx, searched } = context();
    await planTicket(fire({ state: 'open', closing: undefined, closedAt: undefined, text: 'reopened' }), ctx);
    assert.deepEqual(searched, []);
  });
});
