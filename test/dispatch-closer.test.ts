    assert.equal(closedIt({ name: 'Bash', input: { command: 'gh issue close -R acme/other 7' } }, REPO, 7), null);
    assert.equal(closedIt({ name: 'Bash', input: { command: 'gh issue close https://github.com/acme/other/issues/7' } }, REPO, 7), null);
