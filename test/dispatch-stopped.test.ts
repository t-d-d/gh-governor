/**
 * A pickup session that ended without a pull request (dispatch/stopped.mjs):
 * governor takes the claim and the ready labels off its ticket and says so
 * once, whichever sweep finds it, so a person decides and one step starts
 * the ticket again.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { STOPPED_MARKER, releaseStopped, stoppedComment, stoppedOf } from '../dispatch/stopped.mjs';
import { dispatchMarker } from '../dispatch/webhook/fire.mjs';
import { githubReader } from '../scripts/lib/github-app.mjs';
import { promptFor } from '../scripts/lib/dispatch-prompt.mjs';

const FACTORY = 'acme/factory';
const GONE = 'https://claude.ai/code/session_01GONE';
const LIVE = 'https://claude.ai/code/session_01LIVE';
const labels = { ready: ['mode: afk', 'workflow: ready'], claim: 'claimed', claimRemoves: ['workflow: ready'], exclude: ['type: prd'] };
const config = (pickup = true) => ({ labels, features: { pickup } }) as never;
const AT = '2026-11-01T10:00:00.000Z';

type Comment = { id: number, body: string, created_at: string, ours: boolean };
const marker = (sessionUrl: string, id = 1): Comment => ({ id, body: dispatchMarker({ at: AT, sessionUrl }), created_at: AT, ours: true });
const post = (id: number, body: string, ours = false): Comment => ({ id, body, created_at: AT, ours });

/** A reader over open claimed tickets and their threads, recording what it is asked to change. */
const fakeReader = (tickets: Record<number, { labels: string[], comments: Comment[], adds?: Array<{ label: string, at: string }> }>, { failRemove = [] as string[], failComment = false } = {}) => {
  const calls: string[] = [];
  return {
    calls,
    reader: {
      openClaimed: async (claim: string) => Object.entries(tickets).filter(([, t]) => t.labels.includes(claim)).map(([n, t]) => ({ number: Number(n), title: `Ticket ${n}`, labels: [...t.labels] })),
      allComments: async (n: number) => tickets[n]?.comments ?? [],
      // Pickup claimed each ticket just before its dispatch comment, unless a test says otherwise.
      labelAdds: async (n: number) => tickets[n]?.adds ?? [{ label: 'claimed', at: '2026-11-01T09:59:00.000Z' }],
      removeLabel: async (n: number, label: string) => {
        if (failRemove.includes(label)) throw new Error('GitHub answered 502');
        calls.push(`remove #${n} ${label}`);
        const t = tickets[n];
        if (t !== undefined) t.labels = t.labels.filter((l) => l !== label);
      },
      comment: async (n: number, body: string) => {
        if (failComment) throw new Error('GitHub answered 500');
        calls.push(`comment #${n}`);
        tickets[n]?.comments.push(post(1000 + (tickets[n]?.comments.length ?? 0), body, true));
      },
    },
  };
};

/** Session states by id: archived sessions, live ones, and ones the API no longer has. */
const sessions = (states: Record<string, { archived: boolean, branches?: string[] } | null | Error>) => {
  const asked: string[] = [];
  return {
    asked,
    stopped: async (session: string) => {
      asked.push(session);
      const state = states[session];
      if (state instanceof Error) throw state;
      if (state === undefined) throw new Error(`no such fake session ${session}`);
      return state === null ? null : { archived: state.archived, branches: state.branches ?? [] };
    },
  };
};

const logs: Array<[string, Record<string, unknown>]> = [];
const log = (event: string, context: Record<string, unknown> = {}) => { logs.push([event, context]); };

describe('releaseStopped', () => {
  test('a claimed ticket whose dispatched session is archived, with no open PR closing it, loses the claim and the ready labels and gets one comment', async () => {
    const tickets = { 7: { labels: ['claimed', 'mode: afk', 'type: bug'], comments: [marker(GONE), post(2, `I stopped: this needs the owner.\n\n${GONE}\n\n---\n_Generated by Claude Code_`)] } };
    const { reader, calls } = fakeReader(tickets);
    const { stopped } = sessions({ session_01GONE: { archived: true, branches: ['claude/issue-7'] } });
    const done = await releaseStopped({ repo: FACTORY, config: config(), reader, stopped, log });
    assert.deepEqual(done.released, [{ issue: 7, session: 'session_01GONE' }]);
    assert.deepEqual(calls, ['comment #7', 'remove #7 mode: afk', 'remove #7 claimed']);
    assert.deepEqual(tickets[7].labels, ['type: bug']);
    const comment = tickets[7].comments.at(-1)?.body ?? '';
    assert.ok(comment.startsWith(`${STOPPED_MARKER}session_01GONE -->`));
    assert.match(comment, /session_01GONE/);
    assert.match(comment, /https:\/\/github\.com\/acme\/factory\/issues\/7#issuecomment-2/);
    assert.match(comment, /claude\/issue-7/);
  });

  test('the spec owner hears the comment, which the relay sends to nobody', async () => {
    const tickets = { 7: { labels: ['claimed'], comments: [marker(GONE)] } };
    const { reader } = fakeReader(tickets);
    const told: Array<[number, string]> = [];
    await releaseStopped({ repo: FACTORY, config: config(), reader, stopped: sessions({ session_01GONE: { archived: true } }).stopped, log, tell: async (issue: number, comment: string) => { told.push([issue, comment]); } });
    assert.deepEqual(told.map(([n]) => n), [7]);
    assert.equal(told[0]?.[1], tickets[7].comments.at(-1)?.body);
  });

  test('a claim added after the dispatch comment is not the stopped session\'s, and is left alone', async () => {
    const tickets = { 7: { labels: ['claimed'], comments: [marker(GONE)], adds: [{ label: 'claimed', at: '2026-11-01T09:59:00.000Z' }, { label: 'claimed', at: '2026-11-03T08:00:00.000Z' }] } };
    const { reader, calls } = fakeReader(tickets);
    const done = await releaseStopped({ repo: FACTORY, config: config(), reader, stopped: sessions({ session_01GONE: { archived: true } }).stopped, log });
    assert.deepEqual(calls, []);
    assert.deepEqual(done.released, []);
  });

  test('a session the API no longer has counts as ended', async () => {
    const tickets = { 7: { labels: ['claimed'], comments: [marker(GONE)] } };
    const { reader } = fakeReader(tickets);
    const done = await releaseStopped({ repo: FACTORY, config: config(), reader, stopped: sessions({ session_01GONE: null }).stopped, log });
    assert.deepEqual(done.released, [{ issue: 7, session: 'session_01GONE' }]);
    assert.deepEqual(tickets[7].labels, []);
  });

  test('a ticket whose session is not archived is left alone', async () => {
    const tickets = { 7: { labels: ['claimed', 'mode: afk'], comments: [marker(LIVE)] } };
    const { reader, calls } = fakeReader(tickets);
    const done = await releaseStopped({ repo: FACTORY, config: config(), reader, stopped: sessions({ session_01LIVE: { archived: false } }).stopped, log });
    assert.deepEqual(done.released, []);
    assert.deepEqual(calls, []);
  });

  test('the newest dispatch marker decides the session: a ticket taken over by a live session is left alone', async () => {
    const newer = { id: 3, body: dispatchMarker({ at: '2026-11-02T10:00:00.000Z', sessionUrl: LIVE, displaced: GONE }), created_at: '2026-11-02T10:00:00.000Z', ours: true };
    const tickets = { 7: { labels: ['claimed'], comments: [marker(GONE), newer] } };
    const { reader, calls } = fakeReader(tickets);
    const { stopped, asked } = sessions({ session_01GONE: { archived: true }, session_01LIVE: { archived: false } });
    await releaseStopped({ repo: FACTORY, config: config(), reader, stopped, log });
    assert.deepEqual(asked, ['session_01LIVE']);
    assert.deepEqual(calls, []);
  });

  test('a marker a person posted is not governor\'s, and names no session', async () => {
    const tickets = { 7: { labels: ['claimed'], comments: [{ ...marker(GONE), ours: false }] } };
    const { reader, calls } = fakeReader(tickets);
    const { stopped, asked } = sessions({ session_01GONE: { archived: true } });
    await releaseStopped({ repo: FACTORY, config: config(), reader, stopped, log });
    assert.deepEqual(asked, []);
    assert.deepEqual(calls, []);
  });

  test('the comment posts once per stopped session: a later sweep only retries a label that stayed', async () => {
    const tickets = { 7: { labels: ['claimed', 'mode: afk'], comments: [marker(GONE)] } };
    const first = fakeReader(tickets, { failRemove: ['claimed'] });
    const { stopped } = sessions({ session_01GONE: { archived: true } });
    const once = await releaseStopped({ repo: FACTORY, config: config(), reader: first.reader, stopped, log });
    assert.deepEqual(first.calls, ['comment #7', 'remove #7 mode: afk']);
    assert.equal(once.unread.length, 1);
    assert.deepEqual(tickets[7].labels, ['claimed']);
    const again = fakeReader(tickets);
    await releaseStopped({ repo: FACTORY, config: config(), reader: again.reader, stopped, log });
    assert.deepEqual(again.calls, ['remove #7 claimed']);
    assert.equal(tickets[7].comments.filter((c) => c.body.startsWith(STOPPED_MARKER)).length, 1);
  });

  test('a comment that fails takes no label off, so the next sweep tries again', async () => {
    const tickets = { 7: { labels: ['claimed', 'mode: afk'], comments: [marker(GONE)] } };
    const { reader, calls } = fakeReader(tickets, { failComment: true });
    const done = await releaseStopped({ repo: FACTORY, config: config(), reader, stopped: sessions({ session_01GONE: { archived: true } }).stopped, log });
    assert.deepEqual(calls, []);
    assert.deepEqual(done.released, []);
    assert.match(done.unread[0]?.error ?? '', /500/);
  });

  test('a session read that fails releases nothing, and never reads as ended', async () => {
    const tickets = { 7: { labels: ['claimed'], comments: [marker(GONE)] } };
    const { reader, calls } = fakeReader(tickets);
    const done = await releaseStopped({ repo: FACTORY, config: config(), reader, stopped: sessions({ session_01GONE: new Error('sessions API answered 503') }).stopped, log });
    assert.deepEqual(calls, []);
    assert.match(done.unread[0]?.error ?? '', /503/);
  });

  test('given the sessions the sign-off sweep archived, only their tickets are looked at', async () => {
    const tickets = { 7: { labels: ['claimed'], comments: [marker(GONE)] }, 8: { labels: ['claimed'], comments: [marker('https://claude.ai/code/session_01OTHER')] } };
    const { reader } = fakeReader(tickets);
    const { stopped, asked } = sessions({ session_01GONE: { archived: true }, session_01OTHER: { archived: true } });
    const done = await releaseStopped({ repo: FACTORY, config: config(), reader, stopped, log, only: new Set(['session_01GONE']) });
    assert.deepEqual(asked, ['session_01GONE']);
    assert.deepEqual(done.released.map((r) => r.issue), [7]);
    assert.deepEqual(tickets[8].labels, ['claimed']);
  });

  test('a repo whose file turns pickup off is not read', async () => {
    const reader = { openClaimed: async () => { throw new Error('read'); } } as never;
    const done = await releaseStopped({ repo: FACTORY, config: config(false), reader, stopped: async () => { throw new Error('read'); }, log });
    assert.deepEqual(done, { released: [], unread: [] });
  });
});

describe('stoppedComment', () => {
  test('says the session stopped without a PR, what came off, and that the ready labels start a fresh session', () => {
    const text = stoppedComment({ session: 'session_01GONE', removed: ['claimed', 'mode: afk'], ready: ['mode: afk', 'workflow: ready'], last: null, branches: [] });
    assert.match(text, /https:\/\/claude\.ai\/code\/session_01GONE/);
    assert.match(text, /without a pull request/);
    assert.match(text, /`claimed`/);
    assert.match(text, /`mode: afk` and `workflow: ready`/);
    assert.match(text, /fresh session/);
    assert.doesNotMatch(text, /—/);
  });

  test('links the session and its last comment as Markdown links, not bare URLs', () => {
    const last = 'https://github.com/acme/factory/issues/7#issuecomment-55';
    const text = stoppedComment({ session: 'session_01GONE', removed: ['claimed'], ready: ['mode: afk'], last, branches: ['claude/issue-7'] });
    const prose = text.split('\n').slice(1).join('\n');
    assert.match(prose, /\[[^\]]+\]\(https:\/\/claude\.ai\/code\/session_01GONE\)/);
    assert.match(prose, /\[[^\]]+\]\(https:\/\/github\.com\/acme\/factory\/issues\/7#issuecomment-55\)/);
    assert.doesNotMatch(prose.replace(/\]\([^)]*\)/g, ']'), /https:\/\//, 'every URL is a link\'s target');
  });
});

describe('stoppedOf', () => {
  test('a record reads archived or not, with the branches of the repo it pushed', () => {
    const record = { session_status: 'SESSION_STATUS_ARCHIVED', config: { outcomes: [{ git_info: { repo: 'acme/factory', branches: ['claude/issue-7'] } }, { git_info: { repo: 'acme/other', branches: ['x'] } }] } };
    assert.deepEqual(stoppedOf(record, FACTORY), { archived: true, branches: ['claude/issue-7'] });
    assert.deepEqual(stoppedOf({ session_status: 'SESSION_STATUS_IDLE' }, FACTORY), { archived: false, branches: [] });
    assert.equal(stoppedOf(null, FACTORY), null);
    assert.throws(() => stoppedOf({ id: 'cse_1' }, FACTORY), /no status/);
  });
});

describe('the GitHub reader\'s openClaimed', () => {
  test('open claimed issues that no open PR closes, from the one open list', async () => {
    const rows = [
      { number: 7, title: 'Seven', labels: [{ name: 'claimed' }], body: '' },
      { number: 8, title: 'Eight', labels: [{ name: 'claimed' }], body: '' },
      { number: 9, title: 'Nine', labels: [{ name: 'mode: afk' }], body: '' },
      { number: 20, title: 'Fix eight', labels: [], body: 'Closes #8', pull_request: {} },
    ];
    let reads = 0;
    const fetch = (async (url: string) => {
      const u = new URL(url);
      assert.equal(u.pathname, '/repos/acme/factory/issues');
      reads += 1;
      return new Response(JSON.stringify(Number(u.searchParams.get('page') ?? '1') === 1 ? rows : []), { status: 200 });
    }) as unknown as typeof globalThis.fetch;
    const reader = githubReader({ token: 't', repo: FACTORY, appId: 9, fetch });
    assert.deepEqual(await reader.openClaimed('claimed'), [{ number: 7, title: 'Seven', labels: ['claimed'] }]);
    await reader.openClosing(8);
    assert.equal(reads, 1, 'one read of the open list a reader');
  });
});

describe('the default pickup prompt', () => {
  test('tells a fresh session to read the earlier sessions\' comments and carry on from a branch they pushed', () => {
    const prompt = promptFor(700, 'T', 'o/r', 'claimed');
    assert.match(prompt, /If earlier sessions worked on #700, read the comments they left on it first/);
    assert.match(prompt, /carry on from any branch/);
  });
});
