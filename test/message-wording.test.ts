/**
 * The wording of individual governor messages, past the frame every message
 * carries (test/message-frame.test.ts): each says what it means once, in
 * short whole sentences, with no chain of clauses joined by semicolons.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { builderChangeText } from '../dispatch/told.mjs';
import { PROMPTS } from '../dispatch/prompts.mjs';
import { HANDOFF, pullRequestFires, refLine } from '../dispatch/webhook/mention.mjs';
import { titleLink } from '../dispatch/webhook/roles-text.mjs';
import { ownerText, roleNotice } from '../dispatch/dispatch-fire.mjs';
import { promptFor } from '../scripts/lib/dispatch-prompt.mjs';
import { correctionText } from '../dispatch/take.mjs';
import { maybeText, nudgeText } from '../dispatch/author.mjs';
import { editMaybeText, editNudgeText } from '../dispatch/editor.mjs';
import { SESSION_RULES } from '../dispatch/session-rules.mjs';
import { DEPLOYED_MARKER, deployedComment } from '../dispatch/webhook/deployed-comment.mjs';
import { LABEL_PREFIX } from '../dispatch/webhook/fire.mjs';

const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const BUILDER = 'https://claude.ai/code/session_01BUILDER';
const FOOTER = '---\n_Generated by [Claude Code](https://claude.ai/code)_';
const PR_URL = 'https://github.com/acme/factory/pull/12';
const URL = 'https://github.com/acme/factory/issues/7';

/** Two clauses joined by a semicolon, outside a code span. */
const semicolons = (text: string) => assert.doesNotMatch(text.replace(/`[^`]*`/g, ''), /;/, text);

describe('a PR\'s close', () => {
  const close = (merged: boolean) => {
    const pr = {
      number: 12, title: 'The fix', html_url: PR_URL, merged, merged_at: merged ? '2026-11-07T10:00:00Z' : null,
      body: `Closes #7\n\n${SPEC}\n\n${FOOTER}`, user: { login: 'alice', type: 'User' }, author_association: 'OWNER',
      head: { ref: 'fix', sha: 'a'.repeat(40) }, base: { ref: 'main' },
    };
    const { fires } = pullRequestFires({ action: 'closed', pull_request: pr, sender: { login: 'bob', type: 'User' }, repository: { full_name: 'acme/factory', default_branch: 'main' } });
    return JSON.stringify(fires.map((f) => f.fire));
  };

  test('says who merged it, so the login does not read as the PR\'s author', () => {
    const text = close(true);
    assert.match(text, /\[#12 The fix\]\(https:\/\/github\.com\/acme\/factory\/pull\/12\), merged by bob/);
    assert.doesNotMatch(text, /, by bob/);
  });

  test('says who closed it', () => {
    assert.match(close(false), /\[#12 The fix\]\(https:\/\/github\.com\/acme\/factory\/pull\/12\), closed by bob/);
  });
});

describe('a change of builder', () => {
  test('says the issue has a new builder and nothing about the comment kept for people', () => {
    const text = builderChangeText({ issue: 7, title: 'The ticket', url: URL, builder: BUILDER });
    assert.equal(text, `[#7 The ticket](${URL}) has [a new builder](${BUILDER}).`);
  });
});

describe('a takeover of a PR whose session is gone', () => {
  test('is short sentences, not one sentence held together by semicolons', () => {
    assert.match(HANDOFF, /^The session that wrote this PR is gone, so the PR is yours\. /);
    assert.match(HANDOFF, /If it still names another session, put your link there\./);
    semicolons(HANDOFF);
    for (const sentence of HANDOFF.split(/(?<=\.) /)) assert.ok(sentence.split(/\s+/).length <= 20, sentence);
  });
});

describe('a summons that reaches a live session', () => {
  test('to the PR\'s owner, says in one sentence who asked and that it comes to the owner', () => {
    const text = ownerText('The remark.', 'alice');
    const [lead, ...rest] = text.split('\n');
    assert.equal(lead, 'alice asked for a session on this PR, and it comes to you because you own the PR.');
    assert.equal(rest.join('\n'), '\nThe remark.');
  });

  test('to a role holder, says who asked and that it comes to the session for its role', () => {
    const assigned = roleNotice({ issue: 7, assigner: 'alice', remark: null });
    assert.match(assigned, /^alice assigned #7 to claude to ask for a session, and it comes to you because you hold a role on #7\. /);
    assert.match(assigned, /read the ticket and its newest comments/);
    const relayed = roleNotice({ issue: 7, writer: 'bob', remark: null });
    assert.equal(relayed, 'bob asked for a session on #7 in an @claude comment, and it comes to you because you hold a role on #7. The comment reaches you as any comment on the ticket does.');
    const quoted = roleNotice({ issue: 7, writer: 'bob', remark: 'The remark.' });
    assert.equal(quoted, 'bob asked for a session on #7 in an @claude comment, and it comes to you because you hold a role on #7.\n\nThe remark.');
    for (const text of [assigned, relayed, quoted]) semicolons(text);
  });
});

describe('the pickup prompt', () => {
  test('says governor labelled the ticket for this session', () => {
    assert.match(PROMPTS.pickup!.text, /^Governor has labelled #\{issue\} `\{claim\}` for this session\.$/m);
    assert.doesNotMatch(PROMPTS.pickup!.text, /proceed on it/);
  });

  test('gives stopping without a PR a plain sentence of its own', () => {
    const text = promptFor(7, 'The ticket', 'acme/factory', 'claimed', {}, { signOff: true, deployMessages: true });
    assert.match(text, / If you stopped at the check and raised no pull request, there is no pull request to wait for\. /);
    assert.doesNotMatch(text, /no pull request will close/);
  });

  test('a repo\'s own sign-off prompt still follows the sentence', () => {
    const text = promptFor(7, 'The ticket', 'acme/factory', 'claimed', { signOff: 'Say goodbye.' }, { signOff: true });
    assert.match(text, /there is no pull request to wait for\. Say goodbye\.$/);
  });
});

describe('the sign-off ask', () => {
  test('is shorter, has no parenthetical, and keeps its three exceptions', () => {
    const text = PROMPTS.signOff!.text;
    assert.ok(text.split(/\s+/).length <= 40, text);
    assert.doesNotMatch(text, /\(/);
    assert.match(text, /work not on GitHub or in another repo/);
    assert.match(text, /owe a check/);
    assert.match(text, /the operator is working with you/);
    assert.match(text, /`Signing off\.` the last line of your reply/);
    semicolons(text);
  });
});

describe('corrections and nudges', () => {
  const RULE_1 = 'session rule 1: sign everything you write on GitHub.';
  const RULE_2 = "session rule 2: only an issue's or a PR's owner edits its body.";
  const texts = {
    'edit-owned': correctionText(7, 'edit-owned', SPEC),
    'edit-builder': correctionText(7, 'edit-builder', null),
    'edit-person': correctionText(7, 'edit-person', null),
    'edit-pr': correctionText(12, 'edit-pr', SPEC),
    nudge: nudgeText(7, `${URL}#issuecomment-1`),
    maybe: maybeText(7, `${URL}#issuecomment-1`),
    editNudge: editNudgeText(7, URL),
    editMaybe: editMaybeText(7, URL),
  };

  test('none carries the whole session rules block', () => {
    for (const [kind, text] of Object.entries(texts)) {
      assert.ok(!text.includes(SESSION_RULES), kind);
      assert.doesNotMatch(text, /Rules for every session/, kind);
    }
  });

  test('each names the rule broken, by its number', () => {
    for (const kind of ['nudge', 'maybe'] as const) assert.ok(texts[kind].includes(RULE_1), texts[kind]);
    for (const kind of ['edit-owned', 'edit-builder', 'edit-person', 'edit-pr', 'editNudge', 'editMaybe'] as const) assert.ok(texts[kind].includes(RULE_2), texts[kind]);
  });

  test('a message that is not sure the session did it asks only on that condition', () => {
    assert.match(texts.maybe, / If you wrote it, edit it to add this session's link /);
    assert.match(texts.editMaybe, / If you made it, post your change as a comment /);
    for (const text of [texts.maybe, texts.editMaybe]) assert.doesNotMatch(text, /\. (Edit|Post) /, text);
  });
});

describe('the deployed comment', () => {
  test('names the label as a label and the workflow as a link, and keeps the marker', () => {
    const text = deployedComment({ target: 'governor', workflow: 'Deploy', url: 'https://github.com/acme/factory/actions/runs/1/job/2', commit: '52c67fa0123456789' });
    assert.equal(text, `Labelled \`deployed: governor\` by the [Deploy](https://github.com/acme/factory/actions/runs/1/job/2) workflow at 52c67fa.\n\n${DEPLOYED_MARKER}governor -->`);
  });

  test('a bracket in the workflow\'s name does not end the link early', () => {
    const text = deployedComment({ target: 'prod', workflow: 'Ship [prod]', url: 'https://x.test/j', commit: 'abcdef1234' });
    assert.match(text, /the \[Ship \\\[prod\\\]\]\(https:\/\/x\.test\/j\) workflow/);
  });

  test('a backslash ending the workflow\'s name does not escape the link\'s closing bracket', () => {
    const text = deployedComment({ target: 'prod', workflow: 'Ship \\', url: 'https://x.test/j', commit: 'abcdef1234' });
    assert.ok(text.includes('the [Ship \\\\](https://x.test/j) workflow'), text);
  });

  test('names the label with the prefix the label is read by', () => {
    const text = deployedComment({ target: 'prod', workflow: 'Deploy', url: 'https://x.test/j', commit: 'abcdef1234' });
    assert.ok(text.includes(`\`${LABEL_PREFIX}prod\``), text);
  });
});

describe('an issue or PR named with its title', () => {
  test('carries the title inside the link', () => {
    assert.equal(refLine({ number: 7, title: 'The  ticket\n', html_url: URL }), `[#7 The ticket](${URL})`);
    assert.equal(titleLink('PR #12', 'The fix', PR_URL), `[PR #12 The fix](${PR_URL})`);
  });

  test('drops backticks from the title, since a code span in link text shows raw brackets', () => {
    assert.equal(refLine({ number: 7, title: 'Run `npm test` first', html_url: URL }), `[#7 Run npm test first](${URL})`);
  });

  test('a bracket or backslash in the title cannot end the link\'s words early', () => {
    assert.equal(refLine({ number: 7, title: 'Fix [x] \\', html_url: URL }), `[#7 Fix \\[x\\] \\\\](${URL})`);
  });

  test('a PR\'s close puts the title inside the link', () => {
    const pr = {
      number: 12, title: 'The fix', html_url: PR_URL, merged: true, merged_at: '2026-11-07T10:00:00Z',
      body: `Closes #7\n\n${SPEC}\n\n${FOOTER}`, user: { login: 'alice', type: 'User' }, author_association: 'OWNER',
      head: { ref: 'fix', sha: 'a'.repeat(40) }, base: { ref: 'main' },
    };
    const { fires } = pullRequestFires({ action: 'closed', pull_request: pr, sender: { login: 'bob', type: 'User' }, repository: { full_name: 'acme/factory', default_branch: 'main' } });
    assert.match(JSON.stringify(fires.map((f) => f.fire)), /\[#12 The fix\]\(https:\/\/github\.com\/acme\/factory\/pull\/12\), merged by bob/);
  });
});
