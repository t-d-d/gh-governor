/**
 * The receiver's half of a claimed ticket's events (#538, under PRD #535): a
 * comment on an issue, its close and its reopen. The receiver holds no
 * token, so it cannot find a ticket's builders. Where the issue carries the
 * repo's claim label, or the hook table cannot say which label that is, it
 * queues one `ticket` fire in place of the spec owner's message, and the
 * task sends it to both roles (dispatch/ticket-fire.mjs). On a ticket it
 * knows is unclaimed, it queues the spec owner's message as before.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { handle, routeEvent } from '../dispatch/webhook/route.mjs';
import { parseFire } from '../dispatch/webhook/fire.mjs';
import { deployedComment } from '../dispatch/webhook/deployed-comment.mjs';
import { SWITCHES } from '../dispatch/repo-config.mjs';

const SECRET = 'whsec_test';
const REPO = 'acme/factory';
const OWNERS = ['acme'];
const APP_ID = 5075844;
const CLAIM = 'workflow: under development';
const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const BUILDER = 'https://claude.ai/code/session_01BUILDER';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const member = { login: 't-d-d', type: 'User' };
const at = { full_name: REPO, default_branch: 'main' };

const sign = (body: string) => `sha256=${createHmac('sha256', SECRET).update(body).digest('hex')}`;

/** Issue #7, its body ending in the spec owner's link, carrying `labels`. */
const issue = (labels: string[], body = `The spec.\n\n${SPEC}${FOOTER}`, over: Record<string, unknown> = {}) => ({
  number: 7,
  title: 'A ticket',
  state: 'open',
  labels: labels.map((name) => ({ name })),
  html_url: `https://github.com/${REPO}/issues/7`,
  body,
  user: member,
  author_association: 'OWNER',
  assignees: [],
  ...over,
});

const commented = (labels: string[], comment: Record<string, unknown> = {}, on: Record<string, unknown> = {}) => ({
  action: 'created',
  issue: issue(labels, undefined, on),
  comment: { id: 70, body: 'Does this need the empty case too?', html_url: `https://github.com/${REPO}/issues/7#issuecomment-70`, user: member, author_association: 'MEMBER', ...comment },
  repository: at,
  sender: member,
});

const issueEvent = (action: string, labels: string[], over: Record<string, unknown> = {}) => ({
  action,
  issue: issue(labels, undefined, { state: action === 'closed' ? 'closed' : 'open', ...(action === 'closed' ? { state_reason: 'completed' } : {}), ...over }),
  repository: at,
  sender: member,
});

/** The hook-table item the task writes: every switch on but `off`, the ready labels, and the claim label where given. */
const item = (claim: string | undefined, off: string[] = []) => async () => ({
  switches: new Map(SWITCHES.map((name) => [name, !off.includes(name)])),
  ready: ['mode: afk'],
  ...(claim === undefined ? {} : { claim }),
});

const handled = async (event: string, payload: unknown, repoItem: () => Promise<unknown>) => {
  const queued: Array<Record<string, any>> = [];
  const logged: Array<Record<string, unknown>> = [];
  const deps = {
    secret: async () => SECRET,
    hookSecret: async () => 'hook-secret',
    listedHooks: async () => null,
    countFire: async () => 'counted' as const,
    repoItem,
    owners: OWNERS,
    appId: APP_ID,
    enqueue: async (message: Record<string, unknown>) => { queued.push(message); return `m-${queued.length}`; },
    log: (name: string, context: Record<string, unknown> = {}) => { logged.push({ event: name, ...context }); },
  };
  const body = JSON.stringify(payload);
  const response = await handle({ headers: { 'x-github-event': event, 'x-hub-signature-256': sign(body), 'x-github-delivery': 'd-1' }, body, isBase64Encoded: false } as never, deps as never);
  const fires = queued.map((q) => q.fire as Record<string, any>);
  return { response, fires, logged };
};

const ofKind = (fires: Array<Record<string, any>>, kind: string) => fires.filter((f) => f.kind === kind);

describe('the receiver: a claimed ticket\'s comment, close and reopen queue a ticket fire', () => {
  test('a person\'s comment on a claimed ticket: one ticket fire naming the spec owner, in place of its message', async () => {
    const { fires } = await handled('issue_comment', commented([CLAIM, 'mode: afk']), item(CLAIM));
    assert.deepEqual(ofKind(fires, 'message'), []);
    const [ticket, ...more] = ofKind(fires, 'ticket');
    assert.deepEqual(more, []);
    assert.equal(ticket!.issue, 7);
    assert.equal(ticket!.event, 'comments');
    assert.equal(ticket!.state, 'open');
    assert.equal(ticket!.owner, SPEC);
    assert.equal(ticket!.poster, undefined);
    assert.deepEqual(ticket!.labels, [CLAIM, 'mode: afk']);
    assert.match(ticket!.text, /Does this need the empty case too\?/);
    assert.deepEqual(ticket!.authors, ['MEMBER', 'OWNER']);
    // The lane reads back what was queued.
    assert.deepEqual(parseFire(ticket), ticket);
  });

  test('a comment on a ticket the item says is unclaimed: the spec owner\'s message as before, and no ticket fire', async () => {
    const { fires } = await handled('issue_comment', commented(['mode: afk']), item(CLAIM));
    assert.deepEqual(ofKind(fires, 'ticket'), []);
    assert.deepEqual(ofKind(fires, 'message').map((f) => f.session), [SPEC]);
  });

  test('an item without the claim label, no item, or a failed read: the ticket fire is queued, and the task decides', async () => {
    const failing = async () => { throw new Error('ThrottlingException'); };
    for (const [name, read] of [['old item', item(undefined)], ['no item', async () => null], ['failed read', failing]] as const) {
      const { fires } = await handled('issue_comment', commented(['mode: afk']), read);
      assert.deepEqual(ofKind(fires, 'message'), [], name);
      assert.deepEqual(ofKind(fires, 'ticket').map((f) => [f.owner, f.labels]), [[SPEC, ['mode: afk']]], name);
    }
  });

  test('an issue with no labels cannot be claimed: the spec owner\'s message as before, whatever the item says', async () => {
    const { fires } = await handled('issue_comment', commented([]), async () => null);
    assert.deepEqual(ofKind(fires, 'ticket'), []);
    assert.deepEqual(ofKind(fires, 'message').map((f) => f.session), [SPEC]);
  });

  test('a claimed ticket whose body names no session: the ticket fire still goes, naming no spec owner, so its builders hear', async () => {
    const payload = { ...commented([CLAIM]), issue: issue([CLAIM], 'A person wrote this.') };
    const { fires } = await handled('issue_comment', payload, item(CLAIM));
    assert.deepEqual(ofKind(fires, 'ticket').map((f) => [f.issue, f.owner]), [[7, undefined]]);
  });

  test('a session\'s signed comment: the ticket fire names it as the poster, which hears nothing of its own post', async () => {
    const { fires } = await handled('issue_comment', commented([CLAIM], { body: `Built against the real name.\n\n${BUILDER}${FOOTER}` }), item(CLAIM));
    assert.deepEqual(ofKind(fires, 'ticket').map((f) => f.poster), [BUILDER]);
  });

  test('a close and a reopen of a claimed ticket: a ticket fire each, the close closing', async () => {
    const closed = await handled('issues', issueEvent('closed', [CLAIM]), item(CLAIM));
    assert.deepEqual(ofKind(closed.fires, 'message'), []);
    assert.deepEqual(ofKind(closed.fires, 'ticket').map((f) => [f.event, f.state, f.closing, f.owner]), [['close', 'closed', true, SPEC]]);
    assert.match(ofKind(closed.fires, 'ticket')[0]!.text, /was closed \(completed\)/);
    const reopened = await handled('issues', issueEvent('reopened', [CLAIM]), item(CLAIM));
    assert.deepEqual(ofKind(reopened.fires, 'ticket').map((f) => [f.event, f.state, f.closing]), [['close', 'open', undefined]]);
  });

  test('a close of an unclaimed ticket: the spec owner\'s message as before', async () => {
    const { fires } = await handled('issues', issueEvent('closed', ['mode: afk']), item(CLAIM));
    assert.deepEqual(ofKind(fires, 'ticket'), []);
    assert.deepEqual(ofKind(fires, 'message').map((f) => f.session), [SPEC]);
  });

  test('a label change, a comment on a PR, and an edited comment queue no ticket fire', async () => {
    const labelled = await handled('issues', { ...issueEvent('labeled', [CLAIM]), label: { name: 'type: bug' } }, item(CLAIM));
    assert.deepEqual(ofKind(labelled.fires, 'ticket'), []);
    const onPr = await handled('issue_comment', commented([CLAIM], {}, { pull_request: { url: 'x' } }), item(CLAIM));
    assert.deepEqual(ofKind(onPr.fires, 'ticket'), []);
    const edited = await handled('issue_comment', { ...commented([CLAIM]), action: 'edited' }, item(CLAIM));
    assert.deepEqual(ofKind(edited.fires, 'ticket'), []);
  });

  test('with subscribeMessages off, no ticket fire is queued', async () => {
    const { fires } = await handled('issue_comment', commented([CLAIM]), item(CLAIM, ['subscribeMessages']));
    assert.deepEqual([ofKind(fires, 'ticket'), ofKind(fires, 'message')], [[], []]);
  });

  test('a stranger\'s comment, which reaches no session, queues no ticket fire either', async () => {
    const { fires } = await handled('issue_comment', commented([CLAIM], { user: { login: 'stranger', type: 'User' }, author_association: 'NONE' }), item(CLAIM));
    assert.deepEqual(ofKind(fires, 'ticket'), []);
  });

  // Governor's deploy comment is a record for people: the shipping turn
  // tells the ticket's roles itself, so the relay queues nothing for it.
  test('governor\'s deploy comment on a claimed ticket queues no ticket fire and no message', async () => {
    const body = deployedComment({ target: 'prod', workflow: 'Deliver', url: `https://github.com/${REPO}/actions/runs/1/job/2`, commit: 'a'.repeat(40) });
    const bot = { user: { login: 'governor-app[bot]', type: 'Bot' }, author_association: 'NONE', performed_via_github_app: { id: APP_ID }, body };
    const { fires } = await handled('issue_comment', commented([CLAIM], bot), item(CLAIM));
    assert.deepEqual([ofKind(fires, 'ticket'), ofKind(fires, 'message')], [[], []]);
  });

  test('a person\'s comment quoting the deploy marker still reaches the roles', async () => {
    const body = deployedComment({ target: 'prod', workflow: 'Deliver', url: `https://github.com/${REPO}/actions/runs/1/job/2`, commit: 'a'.repeat(40) });
    const { fires } = await handled('issue_comment', commented([CLAIM], { body }), item(CLAIM));
    assert.equal(ofKind(fires, 'ticket').length, 1);
  });
});

describe('routeEvent: the ticket fire waits for the hook table', () => {
  test('routed without a claim label to judge by, the delivery queues what it did before', () => {
    const { fires } = routeEvent({ event: 'issue_comment', payload: commented([CLAIM]), owners: OWNERS });
    assert.deepEqual(fires.map((f) => f.fire.kind), ['message']);
  });
});
