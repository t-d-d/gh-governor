/**
 * A ticket's roles, found one way (dispatch/roles.mjs), as `ownerOf` finds a
 * PR's owner: each session that holds a role once, with its roles and the
 * PRs it owns as a builder, and the "Roles on #N" lines written from them.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { rolesFrom, rolesOf, rolesText } from '../dispatch/roles.mjs';
import { ticketAuthor } from '../dispatch/trust.mjs';
import { dispatchMarker, RELAY } from '../dispatch/webhook/fire.mjs';

const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const BUILDER = 'https://claude.ai/code/session_01BUILDER';
const FOOTER = '---\n_Generated by [Claude Code](https://claude.ai/code)_';
const body = (link: string) => `The spec.\n\n${link}\n\n${FOOTER}`;
const NO_BOT = RELAY.filter((k) => k !== 'BOT');

/** A claimed, open ticket of a member, whose body names the spec owner. */
const row = (over: Record<string, unknown> = {}) => ({ number: 7, title: 'T', body: body(SPEC), state: 'open', labels: ['claimed'], pull: false, author: 'alice', association: 'MEMBER', ...over });

const lookups = ({ open = [] as number[], merged = null as number | null, thread = [] as Array<{ body: string, ours: boolean }>, owners = {} as Record<number, string>, ticket = row() as Record<string, unknown> } = {}) => {
  const asked: string[] = [];
  const reader = {
    ticket: async (n: number) => { asked.push(`ticket ${n}`); return ticket; },
    openClosing: async (n: number) => { asked.push(`open ${n}`); return open.map((number) => ({ number })); },
    closure: async (n: number) => { asked.push(`closure ${n}`); return { pr: merged === null ? null : { number: merged } }; },
    allComments: async (n: number) => { asked.push(`thread ${n}`); return thread; },
  };
  const ownerOf = async (pr: number) => ({ session: owners[pr] ?? null });
  return { reader, ownerOf, asked };
};

describe('rolesOf', () => {
  test('a spec owner that also builds through its open PR is one holder, of both roles, with that PR', async () => {
    const l = lookups({ open: [12], owners: { 12: SPEC } });
    const roles = await rolesOf({ issue: 7, relay: RELAY, claim: 'claimed', reader: l.reader, ownerOf: l.ownerOf });
    assert.deepEqual(roles.holders, [{ session: SPEC, role: 'spec owner and builder', owns: [12], merged: false }]);
    assert.deepEqual([roles.owner, roles.builders, roles.by], [SPEC, [SPEC], 'open PR']);
  });

  test('a spec owner and a separate builder: each once, the spec owner first, the builder with its PRs', async () => {
    const l = lookups({ open: [12, 13], owners: { 12: BUILDER, 13: BUILDER } });
    const roles = await rolesOf({ issue: 7, relay: RELAY, claim: 'claimed', reader: l.reader, ownerOf: l.ownerOf });
    assert.deepEqual(roles.holders, [
      { session: SPEC, role: 'spec owner', owns: [], merged: false },
      { session: BUILDER, role: 'builder', owns: [12, 13], merged: false },
    ]);
  });

  test('a builder found through the PR whose merge closed the ticket is marked merged', async () => {
    const l = lookups({ merged: 20, owners: { 20: BUILDER }, ticket: row({ state: 'closed' }) });
    const roles = await rolesOf({ issue: 7, relay: RELAY, claim: 'claimed', reader: l.reader, ownerOf: l.ownerOf });
    assert.deepEqual(roles.holders[1], { session: BUILDER, role: 'builder', owns: [20], merged: true });
  });

  test('a row handed in is not read again, and an unclaimed ticket looks for no builder', async () => {
    const l = lookups({ thread: [{ body: dispatchMarker({ at: '2026-11-01T00:00:00Z', sessionUrl: BUILDER }), ours: true }] });
    const roles = await rolesOf({ issue: 7, relay: RELAY, claim: 'claimed', ticket: row({ labels: [] }), reader: l.reader, ownerOf: l.ownerOf });
    assert.deepEqual(l.asked, []);
    assert.deepEqual(roles.holders, [{ session: SPEC, role: 'spec owner', owns: [], merged: false }]);
  });

  test('with no claim label handed in, only the spec owner is found, and the row is read once', async () => {
    const l = lookups();
    const roles = await rolesOf({ issue: 7, relay: RELAY, reader: l.reader });
    assert.deepEqual([roles.owner, roles.builders, l.asked], [SPEC, [], ['ticket 7']]);
  });

  test('a ticket governor\'s App filed is judged as the receiver judges it, whatever trust.relay says of bots', async () => {
    const app = row({ author: 'governor-app[bot]', association: 'NONE', app: true });
    assert.equal((await rolesOf({ issue: 7, relay: NO_BOT, ticket: app })).owner, SPEC);
    const bot = row({ author: 'other[bot]', association: 'NONE' });
    assert.equal((await rolesOf({ issue: 7, relay: NO_BOT, ticket: bot })).owner, null);
  });

  test('an owner the caller read is taken as it is', async () => {
    const roles = await rolesOf({ issue: 7, relay: RELAY, ticket: row(), owner: null });
    assert.equal(roles.owner, null);
  });
});

describe('ticketAuthor', () => {
  test('reads the reader\'s app flag as governor\'s own App', () => {
    assert.equal(ticketAuthor({ author: 'x[bot]', app: true }).own, true);
    assert.equal(ticketAuthor({ author: 'x[bot]' }).own, false);
  });
});

describe('rolesText', () => {
  const roles = rolesFrom({ issue: 7, owner: SPEC, builders: [BUILDER], owns: { [BUILDER]: [20] }, by: 'merged PR' });

  test('names both roles and the recipient\'s, the same on every path', () => {
    const text = rolesText(roles, { role: 'spec owner', merged: false });
    assert.equal(text, `You are its spec owner; [its builder](${BUILDER}) is another session.`);
    assert.doesNotMatch(text, /has merged/);
  });

  test('a builder whose PR has merged is told so, and acts only where the message calls for new work', () => {
    const [, builder] = roles.holders;
    const text = rolesText(roles, builder!);
    assert.match(text, /^You are its builder; \[its spec owner\]\(.*SPECOWNER\) is another session\./);
    assert.match(text, /Your PR, which closed #7, has merged: act on this message only where it calls for new work\./);
  });
});
