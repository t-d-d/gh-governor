describe('the receiver: a session\'s unsigned post', () => {
  test('a post no role hears queues an author fire, its post\'s time taken from the payload', async () => {
    const fires = await handled('issue_comment', issueComment());
    const author = fires.filter((f) => f.kind === 'author');
    assert.equal(author.length, 1);
    assert.deepEqual(author[0], { kind: 'author', on: 7, post: POST, authors: ['OWNER'], repo: REPO });
    assert.deepEqual(parseFire(JSON.parse(JSON.stringify(author[0]))), author[0]);
  });

  test('a signed post, a person\'s comment, or sessionRules off queues none', async () => {
    assert.deepEqual(kinds(await handled('issue_comment', issueComment({ body: SIGNED_BODY }))).filter((k) => k === 'author'), []);
    assert.deepEqual(kinds(await handled('issue_comment', issueComment({ body: 'A person writes.' }))).filter((k) => k === 'author'), []);
    assert.deepEqual(kinds(await handled('issue_comment', issueComment(), item(['sessionRules']))).filter((k) => k === 'author'), []);
  });

  test('where a role hears the post, its relay carries the post and no author fire is queued', async () => {
    const fires = await handled('issue_comment', prComment());
    assert.deepEqual(kinds(fires).filter((k) => k === 'author'), []);
    const relay = fires.find((f) => f.kind === 'message');
    assert.ok(relay !== undefined);
    assert.deepEqual(relay.unsigned, { ...POST, url: `https://github.com/${REPO}/pull/12#issuecomment-2` });
    assert.ok(String(relay.text).endsWith(`\n\n${UNSIGNED}`), 'the receiver still writes the line; the task drops it where the search ran');
    assert.deepEqual(parseFire(JSON.parse(JSON.stringify(relay))), relay);
  });

  test('where the relay\'s switch is off, the author fire goes in its place', async () => {
    const fires = await handled('issue_comment', prComment(), item(['prMessages']));
    assert.deepEqual(kinds(fires), ['author']);
    assert.equal(fires[0]!.on, 12);
  });

  test('reviews and review comments are searched as comments are', async () => {
    const reviewed = await handled('pull_request_review', review(), item(['prMessages']));
    assert.deepEqual(reviewed.map((f) => [f.kind, f.on, f.post?.at, f.post?.url]), [['author', 12, POSTED, `https://github.com/${REPO}/pull/12#pullrequestreview-3`]]);
    const commented = await handled('pull_request_review_comment', reviewComment(), item(['prMessages']));
    assert.deepEqual(commented.map((f) => [f.kind, f.on, f.post?.url]), [['author', 12, `https://github.com/${REPO}/pull/12#discussion_r4`]]);
    const heard = await handled('pull_request_review', review());
    assert.ok(heard.some((f) => f.kind === 'message' && f.unsigned?.at === POSTED));
    assert.deepEqual(kinds(heard).filter((k) => k === 'author'), []);
  });

  test('a post on a PR whose body names no session is the branch session\'s, and queues none', async () => {
    const fires = await handled('issue_comment', prComment(`The work.\n\n${FOOTER}`), item(['prMessages']));
    assert.deepEqual(kinds(fires).filter((k) => k === 'author'), []);
  });

  test('a claimed ticket\'s comment carries the post on its ticket fire', () => {
    const decision = routeEvent({ event: 'issue_comment', payload: issueComment({ issueBody: `The spec.\n\n${FOOTER}\n\n${OWNER}`, labels: [CONFIG.labels.claim] }), owners: ['acme'], appId: APP_ID, claim: CONFIG.labels.claim });
    const ticket = decision.fires.find((q) => q.fire.kind === 'ticket')?.fire as Record<string, any>;
    assert.deepEqual(ticket?.unsigned, POST);
    assert.deepEqual(decision.fires.filter((q) => q.fire.kind === 'author'), []);
    assert.deepEqual(parseFire(JSON.parse(JSON.stringify(ticket))), ticket);
  });
});

