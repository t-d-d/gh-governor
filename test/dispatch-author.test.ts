type Sent = { session: string, text: string, opts: Record<string, unknown> };
const accepted = (session: string) => ({ ok: true, answered: true, refused: false, sessionUrl: session, error: null, fallback: null, dropped: null, skipped: null, relinked: null });
const faulted = () => ({ ok: false, answered: false, refused: false, sessionUrl: null, error: 'the CLI printed nothing', fallback: null, dropped: null, skipped: null, relinked: null });

const teller = (told = new Set<string>(), fails: string[] = []) => {
  const sent: Sent[] = [];
  const logged: Array<Record<string, unknown>> = [];
  return {
    sent,
    logged,
    told,
    tellOnce: async (session: string, kind: string) => {
      const key = `${session.slice(session.lastIndexOf('/') + 1)}#${kind}`;
      if (told.has(key)) return false;
      told.add(key);
      return true;
    },
    deliveries: { deliver: async (to: { session?: string }, text: string, opts: Record<string, unknown>) => { sent.push({ session: String(to.session), text, opts }); return fails.includes(String(to.session)) ? faulted() : accepted(String(to.session)); } },
    log: (event: string, context: Record<string, unknown> = {}) => { logged.push({ event, ...context }); },
  };
};

describe('tellAuthor', () => {
  test('the author is nudged once, naming the rule it broke', async () => {
    const t = teller();
    const found = { searched: true as const, author: WRITER, maybe: [], candidates: 2, unread: 0 };
    await tellAuthor({ repo: REPO, on: 7, post: POST, found, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    assert.deepEqual(t.sent.map((s) => [s.session, s.text]), [[WRITER, nudgeText(7, URL_7)]]);
    assert.deepEqual(t.sent[0]!.opts.on, [7]);
    assert.ok(t.sent[0]!.text.includes('session rule 1: sign everything you write on GitHub.'));
    assert.ok(!t.sent[0]!.text.includes(SESSION_RULES));
    assert.ok(t.sent[0]!.text.includes(URL_7));
    const again = teller(t.told);
    await tellAuthor({ repo: REPO, on: 7, post: POST, found, tellOnce: again.tellOnce, deliveries: again.deliveries as never, log: again.log });
    assert.deepEqual(again.sent, []);
  });

  test('undecided: each candidate not ruled out is told the post may be its own', async () => {
    const t = teller();
    await tellAuthor({ repo: REPO, on: 7, post: POST, found: { searched: true, author: null, maybe: [WRITER, OTHER], candidates: 3, unread: 1 }, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    assert.deepEqual(t.sent.map((s) => [s.session, s.text]), [[WRITER, maybeText(7, URL_7)], [OTHER, maybeText(7, URL_7)]]);
    assert.match(maybeText(7, URL_7), /may be yours/);
  });

  test('all ruled out, or no search: nobody is told', async () => {
    const t = teller();
    await tellAuthor({ repo: REPO, on: 7, post: POST, found: { searched: true, author: null, maybe: [], candidates: 2, unread: 0 }, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    await tellAuthor({ repo: REPO, on: 7, post: POST, found: { searched: false, reason: 'no login' }, tellOnce: t.tellOnce, deliveries: t.deliveries as never, log: t.log });
    assert.deepEqual(t.sent, []);
  });

  test('the texts use no em dash', () => {
    assert.doesNotMatch(nudgeText(7, URL_7), /—/);
    assert.doesNotMatch(maybeText(7, URL_7), /—/);
  });
});

describe('relayedText', () => {
  const text = `A comment on an issue you subscribe to.\n\n${UNSIGNED}`;
  test('drops the UNSIGNED line where the search ran, and keeps it where it did not', () => {
    assert.equal(relayedText(text, { searched: true, author: null, maybe: [], candidates: 0, unread: 0 }), 'A comment on an issue you subscribe to.');
    assert.equal(relayedText(text, { searched: false, reason: 'the sessions list could not be read' }), text);
    assert.equal(relayedText(text, null), text);
  });
  test('with the asks off, keeps the UNSIGNED line where the search could not decide, since no candidate is told', () => {
    assert.equal(relayedText(text, { searched: true, author: null, maybe: [OWNER, WRITER], candidates: 2, unread: 0 }, false), text);
    assert.equal(relayedText(text, { searched: true, author: WRITER, maybe: [], candidates: 2, unread: 0 }, false), 'A comment on an issue you subscribe to.');
    assert.equal(relayedText(text, { searched: true, author: null, maybe: [], candidates: 2, unread: 0 }, false), 'A comment on an issue you subscribe to.');
    assert.equal(relayedText(text, { searched: true, author: null, maybe: [OWNER, WRITER], candidates: 2, unread: 0 }), 'A comment on an issue you subscribe to.');
  });
});

/** A TurnContext for planTicket and planAuthor, its search answering `found`. */
const context = ({ found = null as unknown, config = CONFIG, told = new Set<string>(), fails = [] as string[], ticketBody = `The spec.\n\n${FOOTER}\n\n${OWNER}` } = {}) => {
  const sent: Sent[] = [];
  const logged: Array<Record<string, unknown>> = [];
  let searched = 0;
  const reader = {
    ticket: async (n: number) => ({ number: n, id: 9000 + n, title: `Issue ${n}`, body: ticketBody, state: 'open', labels: [config.labels.claim], pull: false, association: 'MEMBER' }),
    allComments: async () => [],
    openClosing: async () => [],
    issue: async (n: number) => ({ number: n, body: ticketBody, pull: false }),
  };
  const ctx = {
    readerFor: async () => reader,
    configOf: () => config,
    served: [],
    bare: false,
    prompts: config.prompts,
    delivery: () => ({
      deliver: async (to: { session?: string }, text: string, opts: Record<string, unknown>) => { sent.push({ session: String(to.session), text, opts }); return fails.includes(String(to.session)) ? faulted() : accepted(String(to.session)); },
      ownerOf: async () => null,
    }),
    storeLogin: async () => false,
    state: {
      recordTold: async (session: string, kind: string) => {
        const key = `${session.slice(session.lastIndexOf('/') + 1)}#${kind}`;
        if (told.has(key)) return false;
        told.add(key);
        return true;
      },
    },
    start: async () => { throw new Error('this starts nothing'); },
    open: async () => true,
    claims: new Set<string>(),
    beats: [],
    now: () => LATE,
    log: (event: string, c: Record<string, unknown> = {}) => { logged.push({ event, ...c }); },
    sleep: async () => {},
    cap: 2,
    findAuthor: async () => { searched += 1; return found; },
  };
  return { ctx: ctx as never, sent, logged, searched: () => searched };
};

const ticketFire = (over: Record<string, unknown> = {}) => ({
  kind: 'ticket', repo: REPO, issue: 7, text: `A comment on an issue you subscribe to.\n\n${UNSIGNED}`, event: 'comments', state: 'open', labels: [CONFIG.labels.claim], owner: OWNER, authors: ['OWNER'], unsigned: POST, ...over,
}) as never;

describe('planTicket: an unsigned comment on a claimed ticket', () => {
  test('a spec owner that wrote it is not relayed its own post, and is nudged once', async () => {
    const { ctx, sent } = context({ found: { searched: true, author: OWNER, maybe: [], candidates: 1, unread: 0 } });
    const plan = await planTicket(ticketFire(), ctx) as any;
    assert.deepEqual(sent.map((s) => s.session), [OWNER]);
    assert.equal(sent[0]!.text, nudgeText(7, URL_7));
    assert.equal(exitCodeFor(plan.answer), 0);
  });

  test('another session wrote it: the spec owner hears it without UNSIGNED, and the writer is nudged', async () => {
    const { ctx, sent } = context({ found: { searched: true, author: WRITER, maybe: [], candidates: 2, unread: 0 } });
    await planTicket(ticketFire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER, WRITER]);
    assert.ok(!sent[0]!.text.includes(UNSIGNED));
    assert.match(sent[0]!.text, /^A comment on an issue you subscribe to\./);
  });

  test('the sessions list could not be read: the relay keeps UNSIGNED, and nobody is nudged', async () => {
    const { ctx, sent } = context({ found: { searched: false, reason: 'the sessions list could not be read' } });
    await planTicket(ticketFire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER]);
    assert.ok(sent[0]!.text.includes(UNSIGNED));
  });

  test('with sessionRules off, a spec owner that wrote it is not relayed its own post, and is not asked to sign it', async () => {
    const told = new Set<string>();
    const { ctx, sent, searched } = context({ config: RULES_OFF, told, found: { searched: true, author: OWNER, maybe: [], candidates: 1, unread: 0 } });
    const plan = await planTicket(ticketFire(), ctx) as any;
    assert.equal(searched(), 1);
    assert.deepEqual(sent, []);
    assert.deepEqual([...told], []);
    assert.equal(exitCodeFor(plan.answer), 0);
  });

  test('with sessionRules off, another session wrote it: the owner hears it without UNSIGNED, and the writer is not asked to sign it', async () => {
    const { ctx, sent } = context({ config: RULES_OFF, found: { searched: true, author: WRITER, maybe: [], candidates: 2, unread: 0 } });
    await planTicket(ticketFire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER]);
    assert.ok(!sent[0]!.text.includes(UNSIGNED));
  });

  test('with sessionRules off, undecided: the relay keeps UNSIGNED and no candidate is told', async () => {
    const { ctx, sent } = context({ config: RULES_OFF, found: { searched: true, author: null, maybe: [OWNER, WRITER], candidates: 2, unread: 0 } });
    await planTicket(ticketFire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [OWNER]);
    assert.ok(sent[0]!.text.includes(UNSIGNED));
  });

  test('with sessionRules off, nothing is searched where no session could hear the comment', async () => {
    const { ctx, sent, searched } = context({ config: RULES_OFF, found: { searched: true, author: WRITER, maybe: [], candidates: 2, unread: 0 } });
    const plan = await planTicket(ticketFire({ labels: ['mode: afk'], owner: undefined }), ctx) as any;
    assert.equal(searched(), 0);
    assert.deepEqual(sent, []);
    assert.equal(exitCodeFor(plan.answer), 0);
  });

  test('a nudge that faults fails the turn', async () => {
    const { ctx } = context({ found: { searched: true, author: WRITER, maybe: [], candidates: 1, unread: 0 }, fails: [WRITER] });
    const plan = await planTicket(ticketFire(), ctx) as any;
    assert.equal(exitCodeFor(plan.answer), 1);
  });
});

