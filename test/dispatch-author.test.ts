/**
 * The author of a session's unsigned post (#616, under PRD #599). A
 * comment, a review or a review comment that ends in the Claude Code footer
 * and names no session could be any session's. Under `sessionRules`
 * governor searches the login's live sessions working in the post's repo
 * for the tool call that posted it, in windows anchored on the post's own
 * time:
 *
 * - one match: that session is told once to sign its post, and a role that
 *   wrote it is not relayed its own post;
 * - undecided (two matches, or events that cannot be read): each candidate
 *   not ruled out is told once the post may be its own;
 * - all ruled out: nobody is told.
 *
 * The relay drops its `UNSIGNED` line where the search ran, and keeps it
 * where the sessions list could not be read. A post no role hears queues an
 * `author` fire of its own, under `sessionRules` alone.
 */

