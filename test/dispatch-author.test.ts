/** A tool call event at `when` (ms). */
const call = (when: number, name: string, input: Record<string, unknown>, id = `e-${when}-${name}`) => ({
  event_id: id,
  event_type: 'assistant',
  created_at: new Date(when).toISOString(),
  payload: { type: 'assistant', message: { content: [{ type: 'tool_use', id: `t-${id}`, name, input }] } },
});
const said = (when: number) => ({ event_id: `s-${when}`, event_type: 'assistant', created_at: new Date(when).toISOString(), payload: { type: 'assistant', message: { content: [{ type: 'text', text: WORDS }] } } });
const mcpComment = (when: number, body = UNSIGNED_BODY, issue = 7) => call(when, 'mcp__github__add_issue_comment', { owner: 'acme', repo: 'factory', issue_number: issue, body });
const row = (id: string, { updated = AT, repo = REPO, status = 'SESSION_STATUS_IDLE' } = {}) => ({
  id: `cse_${id}`,
  session_status: status,
  updated_at: new Date(updated).toISOString(),
  config: { sources: [{ url: `https://github.com/${repo}` }] },
});

/** A sessions API: `rows` listed, each session's events newest first in one page, unless `fails` names it. */
const api = (rows: unknown[], events: Record<string, unknown[]>, { fails = [] as string[], listFails = false } = {}) => {
  const read: string[] = [];
  return {
    read,
    list: async () => { if (listFails) throw new Error('GET /v1/code/sessions: 503'); return rows; },
    events: async (id: string) => {
      read.push(id);
      if (fails.includes(id)) throw new Error('GET events: 502');
      return { data: [...(events[id] ?? [])].sort((a: any, b: any) => Date.parse(b.created_at) - Date.parse(a.created_at)), next_cursor: null };
    },
  };
};

