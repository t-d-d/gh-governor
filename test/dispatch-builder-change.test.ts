/**
 * A change of builder is announced (#540, under PRD #535). Governor posts
 * its dispatch comment on a ticket whenever the builder changes: at pickup's
 * launch, at a takeover of a PR that closes the ticket, and when a PR by a
 * session other than the builder comes to close a claimed ticket. The
 * comment reaches the ticket's spec owner, and the builder it displaced
 * where that session is live and is not the new one, which is asked to stop
 * and sign off. It never reaches the builder it names. Only a comment
 * governor's App posted counts: a marker anyone else writes reaches nobody.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { handle } from '../dispatch/webhook/route.mjs';
import { dispatchMarker, dispatchedTo, lastDispatch, parseFire, RELAY } from '../dispatch/webhook/fire.mjs';
import { switchOf } from '../dispatch/webhook/switches.mjs';
import { SWITCHES, readConfig, type RepoConfig } from '../dispatch/repo-config.mjs';
import { planClosingPr, planTicket } from '../dispatch/ticket-fire.mjs';
import { GITHUB_SOURCE, deliveries } from '../dispatch/deliveries.mjs';
import { factoryFile } from './helpers/factory.ts';

const SECRET = 'whsec_test';
const REPO = 'acme/factory';
const OWNERS = ['acme'];
const APP_ID = 5075844;
const NOW = Date.parse('2026-11-06T12:00:00Z');
const CONFIG = (() => {
  const read = readConfig(factoryFile('.github/governor.json'));
  assert.ok(read.ok);
  return read.config as RepoConfig;
})();
const CLAIM = CONFIG.labels.claim;
const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const BUILDER = 'https://claude.ai/code/session_01BUILDER';
const OTHER = 'https://claude.ai/code/session_01OTHER';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const member = { login: 't-d-d', type: 'User' };
const app = { user: { login: 'governor-app[bot]', type: 'Bot' }, author_association: 'NONE', performed_via_github_app: { id: APP_ID } };
const at = { full_name: REPO, default_branch: 'main' };
const stamp = (ms = NOW) => new Date(ms).toISOString();

// ── The receiver ────────────────────────────────────────────────────────

const sign = (body: string) => `sha256=${createHmac('sha256', SECRET).update(body).digest('hex')}`;

const issue = (labels: string[], body = `The spec.\n\n${SPEC}${FOOTER}`) => ({
  number: 7,
  title: 'A ticket',
  state: 'open',
  labels: labels.map((name) => ({ name })),
  html_url: `https://github.com/${REPO}/issues/7`,
  body,
  user: member,
  author_association: 'OWNER',
  assignees: [],
});

const commented = (labels: string[], comment: Record<string, unknown>) => ({
  action: 'created',
  issue: issue(labels),
  comment: { id: 70, html_url: `https://github.com/${REPO}/issues/7#issuecomment-70`, ...comment },
  repository: at,
  sender: comment.user ?? member,
});

const pull = (action: string, body: string, over: Record<string, unknown> = {}) => ({
  action,
  number: 9,
  pull_request: {
    number: 9,
    state: 'open',
    title: 'Build the ticket',
    html_url: `https://github.com/${REPO}/pull/9`,
    body,
    user: member,
    author_association: 'OWNER',
    head: { ref: 'claude/other', sha: 'a'.repeat(40) },
    base: { ref: 'main' },
    merged: false,
  },
  repository: at,
  sender: member,
  ...over,
});

const item = (off: string[] = []) => async () => ({
  switches: new Map(SWITCHES.map((name) => [name, !off.includes(name)])),
  ready: ['mode: afk'],
  claim: CLAIM,
});

const handled = async (event: string, payload: unknown, repoItem = item()) => {
  const queued: Array<Record<string, any>> = [];
  const deps = {
    secret: async () => SECRET,
    hookSecret: async () => 'hook-secret',
    listedHooks: async () => null,
    countFire: async () => 'counted' as const,
    repoItem,
    owners: OWNERS,
    appId: APP_ID,
    enqueue: async (message: Record<string, unknown>) => { queued.push(message); return `m-${queued.length}`; },
    log: () => {},
  };
  const body = JSON.stringify(payload);
  await handle({ headers: { 'x-github-event': event, 'x-hub-signature-256': sign(body), 'x-github-delivery': 'd-1' }, body, isBase64Encoded: false } as never, deps as never);
  return queued.map((q) => q.fire as Record<string, any>);
};

const ofKind = (fires: Array<Record<string, any>>, kind: string) => fires.filter((f) => f.kind === kind);

describe('the dispatch comment says who builds the ticket, and whom it displaced', () => {
  test('pickup\'s comment names its session and displaces nobody', () => {
    const body = dispatchMarker({ at: stamp(), sessionUrl: BUILDER });
    assert.deepEqual(dispatchedTo(body), { builder: BUILDER, displaced: null });
    assert.equal(lastDispatch([{ body }])?.sessionUrl, BUILDER);
  });

  test('a change of builder names the new session and the one it displaced, and the lookup still reads the new one', () => {
    const body = dispatchMarker({ at: stamp(), sessionUrl: OTHER, displaced: BUILDER });
    assert.deepEqual(dispatchedTo(body), { builder: OTHER, displaced: BUILDER });
    assert.equal(lastDispatch([{ body }])?.sessionUrl, OTHER);
    assert.match(body, /^<!-- governor:dispatched \S+ -->\n/, 'the marker is unchanged');
  });
});

describe('the receiver: governor\'s dispatch comment is relayed', () => {
  test('pickup\'s launch comment queues a ticket fire naming the builder, for the spec owner, claimed or not', async () => {
    for (const labels of [[CLAIM, 'mode: afk'], ['mode: afk'], []]) {
      const fires = await handled('issue_comment', commented(labels, { ...app, body: dispatchMarker({ at: stamp(), sessionUrl: BUILDER }) }));
      assert.deepEqual(ofKind(fires, 'message'), [], JSON.stringify(labels));
      const [ticket, ...more] = ofKind(fires, 'ticket');
      assert.deepEqual(more, []);
      assert.equal(ticket!.event, 'dispatched');
      assert.equal(ticket!.builder, BUILDER);
      assert.equal(ticket!.displaced, undefined);
      assert.equal(ticket!.owner, SPEC);
      assert.match(ticket!.text, /#7/);
      assert.deepEqual(parseFire(ticket), ticket);
    }
  });

  test('a change of builder\'s comment names the session it displaced', async () => {
    const fires = await handled('issue_comment', commented([CLAIM], { ...app, body: dispatchMarker({ at: stamp(), sessionUrl: OTHER, displaced: BUILDER }) }));
    assert.deepEqual(ofKind(fires, 'ticket').map((f) => [f.builder, f.displaced]), [[OTHER, BUILDER]]);
  });

  test('a dispatch marker in a comment governor\'s App did not post queues nothing for anyone', async () => {
    const forged = dispatchMarker({ at: stamp(NOW + 86_400_000), sessionUrl: OTHER, displaced: BUILDER });
    for (const by of [{ user: member, author_association: 'MEMBER' }, { user: { login: 'other-app[bot]', type: 'Bot' }, author_association: 'NONE', performed_via_github_app: { id: 1 } }]) {
      const fires = await handled('issue_comment', commented([CLAIM], { ...by, body: forged }));
      assert.deepEqual(fires, [], JSON.stringify(by));
    }
  });

  test('with subscribeMessages off, the dispatch comment is relayed to nobody', async () => {
    const fires = await handled('issue_comment', commented([CLAIM], { ...app, body: dispatchMarker({ at: stamp(), sessionUrl: BUILDER }) }), item(['subscribeMessages']));
    assert.deepEqual(fires, []);
  });
});

describe('the receiver: a PR that comes to close a ticket queues a closingPr fire', () => {
  test('a PR opened closing a ticket queues one fire naming the PR, under subscribeMessages', async () => {
    const fires = await handled('pull_request', pull('opened', `Closes #7\n\n${OTHER}`));
    const [fire, ...more] = ofKind(fires, 'closingPr');
    assert.deepEqual(more, []);
    assert.deepEqual(fire, { kind: 'closingPr', pr: 9, repo: REPO });
    assert.deepEqual(parseFire(fire), fire);
    assert.equal(switchOf(fire as never), 'subscribeMessages');
  });

  test('a PR edited to close a ticket queues the fire; an edit that closes nothing new does not', async () => {
    const added = await handled('pull_request', pull('edited', `Closes #7\n\n${OTHER}`, { changes: { body: { from: `The work.\n\n${OTHER}` } } }));
    assert.equal(ofKind(added, 'closingPr').length, 1);
    const same = await handled('pull_request', pull('edited', `Closes #7\n\nMore words.\n\n${OTHER}`, { changes: { body: { from: `Closes #7\n\n${OTHER}` } } }));
    assert.deepEqual(ofKind(same, 'closingPr'), []);
    const titled = await handled('pull_request', pull('edited', `Closes #7\n\n${OTHER}`, { changes: { title: { from: 'Old' } } }));
    assert.deepEqual(ofKind(titled, 'closingPr'), []);
  });

  test('a PR that closes nothing, a stranger\'s PR, and a switch turned off queue nothing', async () => {
    assert.deepEqual(ofKind(await handled('pull_request', pull('opened', `The work.\n\n${OTHER}`)), 'closingPr'), []);
    const stranger = pull('opened', 'Closes #7');
    stranger.pull_request.user = { login: 'stranger', type: 'User' };
    stranger.pull_request.author_association = 'NONE';
    assert.deepEqual(ofKind(await handled('pull_request', stranger), 'closingPr'), []);
    assert.deepEqual(ofKind(await handled('pull_request', pull('opened', 'Closes #7'), item(['subscribeMessages'])), 'closingPr'), []);
  });
});

// ── The task: relaying the comment ──────────────────────────────────────

type Sent = { session: string, text: string, opts: Record<string, unknown> };

const TEXT = 'Issue #7: A ticket (https://github.com/acme/factory/issues/7) has a new builder.';
const dispatched = (over: Record<string, unknown> = {}) => ({ kind: 'ticket', repo: REPO, issue: 7, text: TEXT, event: 'dispatched', state: 'open', labels: [CLAIM], owner: SPEC, builder: BUILDER, authors: [], ...over }) as never;

const relayContext = ({ archived = [] as string[] } = {}) => {
  const sent: Sent[] = [];
  const reads: string[] = [];
  const ctx = {
    readerFor: async () => { reads.push('reader'); return {}; },
    configOf: () => CONFIG,
    delivery: () => ({
      ownerOf: async () => { reads.push('ownerOf'); return { session: null }; },
      deliver: async ({ session }: { session: string }, text: string, opts: Record<string, unknown>) => {
        sent.push({ session, text, opts });
        const gone = archived.includes(session);
        return { ok: !gone, answered: true, refused: gone, sessionUrl: session, error: gone ? 'archived' : null, fallback: null, dropped: null, skipped: null, relinked: null };
      },
    }),
    storeLogin: async () => true,
    now: () => NOW,
    log: () => {},
  };
  return { ctx: ctx as never, sent, reads };
};

describe('planTicket: governor\'s dispatch comment reaches the spec owner and the displaced builder', () => {
  test('pickup\'s launch comment reaches the spec owner, naming the builder, and not the builder; nothing is read', async () => {
    const { ctx, sent, reads } = relayContext();
    await planTicket(dispatched(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [SPEC]);
    assert.ok(sent[0]!.text.startsWith(TEXT), sent[0]!.text);
    assert.match(sent[0]!.text, new RegExp(`builder is ${BUILDER}`));
    assert.match(sent[0]!.text, /You are its spec owner\./);
    assert.match(sent[0]!.text, /notice/);
    assert.doesNotMatch(sent[0]!.text, /sign off/);
    assert.deepEqual(reads, []);
  });

  test('a spec session that is its own builder hears nothing of its own launch', async () => {
    const { ctx, sent } = relayContext();
    await planTicket(dispatched({ owner: BUILDER }), ctx);
    assert.deepEqual(sent, []);
  });

  test('a live displaced builder is told another session builds the ticket, and asked to stop and sign off', async () => {
    const { ctx, sent } = relayContext();
    await planTicket(dispatched({ builder: OTHER, displaced: BUILDER }), ctx);
    assert.deepEqual(sent.map((s) => s.session), [SPEC, BUILDER]);
    assert.match(sent[0]!.text, new RegExp(`builder is ${OTHER}`));
    assert.doesNotMatch(sent[0]!.text, /sign off/);
    const told = sent[1]!.text;
    assert.ok(told.startsWith(TEXT), told);
    assert.match(told, new RegExp(`no longer build #7: ${OTHER} does`));
    assert.match(told, /stop/i);
    assert.match(told, /sign off unless you know a reason not to/);
    assert.equal(sent[1]!.opts.closing, true);
    assert.deepEqual(sent[1]!.opts.on, [7]);
  });

  test('a displaced builder that is the new builder, or archived, asks nothing of anyone', async () => {
    const same = relayContext();
    await planTicket(dispatched({ builder: BUILDER, displaced: BUILDER }), same.ctx);
    assert.deepEqual(same.sent.map((s) => s.session), [SPEC]);
    const gone = relayContext({ archived: [BUILDER] });
    const plan = await planTicket(dispatched({ builder: OTHER, displaced: BUILDER }), gone.ctx) as any;
    assert.deepEqual(gone.sent.map((s) => s.session), [SPEC, BUILDER]);
    assert.equal(plan.answer.messaged.ok, true, 'a gone builder is no fault');
  });

  test('a spec owner that built its own ticket is told it no longer builds it, and stays its spec owner', async () => {
    const { ctx, sent } = relayContext();
    await planTicket(dispatched({ builder: OTHER, displaced: SPEC }), ctx);
    assert.deepEqual(sent.map((s) => s.session), [SPEC]);
    assert.match(sent[0]!.text, new RegExp(`no longer build #7: ${OTHER} does`));
    assert.match(sent[0]!.text, /remain its spec owner/);
    assert.doesNotMatch(sent[0]!.text, /sign off/);
  });

  test('on a ticket no session link ends, only the displaced builder hears', async () => {
    const { ctx, sent } = relayContext();
    await planTicket(dispatched({ owner: undefined, builder: OTHER, displaced: BUILDER }), ctx);
    assert.deepEqual(sent.map((s) => s.session), [BUILDER]);
  });
});

// ── The task: a PR that comes to close a claimed ticket ─────────────────

type Thread = Array<{ body: string, ours: boolean }>;

/**
 * A turn context whose reader holds PR 9 and ticket 7. `closing`: the open
 * PRs that close 7, PR 9 among them; `owners`: each PR's owner; `thread`:
 * 7's comments; `labels`, `state`, `body`: ticket 7's.
 */
const prContext = ({
  prBody = `Closes #7\n\n${OTHER}`,
  open = true,
  closing = [9] as number[],
  owners = { 9: OTHER } as Record<number, string>,
  thread = [{ body: dispatchMarker({ at: stamp(NOW - 3_600_000), sessionUrl: BUILDER }), ours: true }] as Thread,
  labels = [CLAIM],
  state = 'open',
  body = `The spec.\n\n${SPEC}${FOOTER}`,
} = {}) => {
  const posted: Array<{ issue: number, body: string }> = [];
  const logged: Array<Record<string, unknown>> = [];
  const reader = {
    pull: async (n: number) => ({ number: n, body: prBody, head: 'claude/other', defaultBranch: 'main', open }),
    ticket: async (n: number) => ({ number: n, title: 'A ticket', body, state, labels, pull: false, author: 't-d-d', association: 'OWNER' }),
    openClosing: async () => closing.map((number) => ({ number, title: `PR ${number}`, html_url: `u${number}` })),
    closure: async () => ({ pr: null }),
    allComments: async () => thread.map((c, i) => ({ id: i, created_at: stamp(), ...c })),
    comment: async (n: number, text: string) => { posted.push({ issue: n, body: text }); },
  };
  const ctx = {
    readerFor: async () => reader,
    configOf: () => CONFIG,
    delivery: () => ({ ownerOf: async (pr: number) => ({ session: owners[pr] ?? null, branch: '', linked: true }) }),
    now: () => NOW,
    log: (event: string, context: Record<string, unknown> = {}) => { logged.push({ event, ...context }); },
  };
  return { ctx: ctx as never, posted, logged };
};

const closingPr = { kind: 'closingPr', repo: REPO, pr: 9 } as never;

describe('planClosingPr: a PR by another session that closes a claimed ticket names it the builder', () => {
  test('a PR by a session other than the builder posts a dispatch comment naming it, and the builder it displaced', async () => {
    const { ctx, posted } = prContext();
    await planClosingPr(closingPr, ctx);
    assert.equal(posted.length, 1);
    assert.equal(posted[0]!.issue, 7);
    assert.deepEqual(dispatchedTo(posted[0]!.body), { builder: OTHER, displaced: BUILDER });
    assert.equal(lastDispatch([{ body: posted[0]!.body }])?.at, stamp());
  });

  test('the builder\'s own PR posts nothing', async () => {
    const { ctx, posted } = prContext({ owners: { 9: BUILDER } });
    await planClosingPr(closingPr, ctx);
    assert.deepEqual(posted, []);
  });

  test('a second PR edit after the comment posts nothing more', async () => {
    const { ctx, posted } = prContext({ thread: [
      { body: dispatchMarker({ at: stamp(NOW - 3_600_000), sessionUrl: BUILDER }), ours: true },
      { body: dispatchMarker({ at: stamp(NOW - 60_000), sessionUrl: OTHER, displaced: BUILDER }), ours: true },
    ] });
    await planClosingPr(closingPr, ctx);
    assert.deepEqual(posted, []);
  });

  test('a second open PR beside the builder\'s own names the new session and displaces nobody', async () => {
    const { ctx, posted } = prContext({ closing: [8, 9], owners: { 8: BUILDER, 9: OTHER } });
    await planClosingPr(closingPr, ctx);
    assert.equal(posted.length, 1);
    assert.deepEqual(dispatchedTo(posted[0]!.body), { builder: OTHER, displaced: null });
  });

  test('a spec session that claimed and built its own ticket is the builder displaced', async () => {
    const { ctx, posted } = prContext({ thread: [] });
    await planClosingPr(closingPr, ctx);
    assert.deepEqual(dispatchedTo(posted[0]!.body), { builder: OTHER, displaced: SPEC });
  });

  test('a dispatch marker governor\'s App did not post names no builder to displace', async () => {
    const forged = { body: dispatchMarker({ at: stamp(NOW + 86_400_000), sessionUrl: BUILDER }), ours: false };
    const { ctx, posted } = prContext({ thread: [forged], body: 'A person wrote this.' });
    await planClosingPr(closingPr, ctx);
    assert.deepEqual(dispatchedTo(posted[0]!.body), { builder: OTHER, displaced: null });
  });

  test('an unclaimed ticket, a closed ticket, a closed PR, and a PR no session holds post nothing', async () => {
    for (const over of [{ labels: ['mode: afk'] }, { state: 'closed' }, { open: false }, { owners: {} }]) {
      const { ctx, posted } = prContext(over);
      await planClosingPr(closingPr, ctx);
      assert.deepEqual(posted, [], JSON.stringify(over));
    }
  });

  test('end to end: the comment posted reaches the spec owner and asks the live displaced builder to sign off', async () => {
    const { ctx, posted } = prContext();
    await planClosingPr(closingPr, ctx);
    const fires = await handled('issue_comment', commented([CLAIM], { ...app, body: posted[0]!.body }));
    const [ticket] = ofKind(fires, 'ticket');
    const relay = relayContext();
    await planTicket(parseFire(ticket) as never, relay.ctx);
    assert.deepEqual(relay.sent.map((s) => s.session), [SPEC, BUILDER]);
    assert.match(relay.sent[1]!.text, /sign off unless you know a reason not to/);
  });
});

// ── A takeover ──────────────────────────────────────────────────────────

describe('a takeover of a PR that closes a ticket posts the dispatch comment on the ticket', () => {
  const PR_BODY = `Closes #7\n\n## Outcome\n\nThe work.\n\n${BUILDER}`;
  const archived = async ({ session }: { session: string }) => ({ status: 1, output: JSON.stringify({ ok: false, session_id: session, error: `cloud session ${session} is archived and cannot accept new messages` }) });
  const accepted = (session: string) => ({ status: 0, output: JSON.stringify({ ok: true, session_id: session, url: `https://claude.ai/code/${session}` }) });

  const fakes = ({ send, sessions = async () => null as string | null, prBody = PR_BODY }: { send: (m: { session: string }) => Promise<{ status: number, output: string }>, sessions?: (branch: string) => Promise<string | null>, prBody?: string }) => {
    const comments: Array<{ issue: number, body: string }> = [];
    const edits: Array<{ pr: number, body: string }> = [];
    let body = prBody;
    const reader = {
      comments: async () => [],
      comment: async (n: number, text: string) => { comments.push({ issue: n, body: text }); },
      pull: async (n: number) => ({ number: n, body, head: 'claude/branch-9', defaultBranch: 'main', open: true, author: 't-d-d', association: 'OWNER', bot: false, own: false }),
      updatePull: async (n: number, change: { body: string }) => { edits.push({ pr: n, body: change.body }); body = change.body; },
      issue: async (n: number) => ({ number: n, body: '', pull: false }),
      updateIssue: async () => {},
      openNaming: async () => [],
      openPulls: async () => [],
      commit: async (sha: string) => ({ sha, message: '' }),
    };
    const delivery = deliveries({
      prompts: CONFIG.prompts as never,
      signOff: true,
      reader: async () => reader as never,
      repo: REPO,
      relay: RELAY,
      send: async (m: { session: string, text: string }) => send(m),
      launch: async () => ({ outcome: 'dispatched', sessionUrl: OTHER }),
      sessions: () => sessions,
      now: () => NOW,
      log: () => {},
      sleep: async () => {},
    });
    return { delivery, comments, edits };
  };
  const fallback = { prompt: 'Take the PR over.', sessionName: 'PR 9', issue: 9 };

  test('a takeover that starts a session names it on each ticket the PR closes', async () => {
    const f = fakes({ send: archived });
    await f.delivery.deliver({ session: BUILDER }, 'a remark', { source: GITHUB_SOURCE, fallback, takeover: true } as never);
    assert.equal(f.edits.length, 1, 'the PR body is relinked');
    assert.deepEqual(f.comments.map((c) => c.issue), [7]);
    assert.deepEqual(dispatchedTo(f.comments[0]!.body), { builder: OTHER, displaced: null });
  });

  test('a branch session written into the PR body in place of an archived owner is named on the ticket', async () => {
    const LIVE = 'https://claude.ai/code/session_01LIVE';
    const f = fakes({ send: async (m) => (m.session === BUILDER ? archived(m) : accepted('session_01LIVE')), sessions: async (branch) => (branch === 'claude/branch-9' ? LIVE : null) });
    await f.delivery.deliver({ session: BUILDER }, 'a remark', { source: GITHUB_SOURCE, fallback, takeover: true } as never);
    assert.deepEqual(f.comments.map((c) => [c.issue, dispatchedTo(c.body).builder]), [[7, LIVE]]);
  });

  test('a branch session written into a PR body that named nobody is no change of builder: nothing is posted', async () => {
    const LIVE = 'https://claude.ai/code/session_01LIVE';
    const f = fakes({ send: async () => accepted('session_01LIVE'), sessions: async () => LIVE, prBody: 'Closes #7\n\nThe work.' });
    await f.delivery.deliver({ pr: 9 }, 'a remark', { source: GITHUB_SOURCE } as never);
    assert.equal(f.edits.length, 1, 'the body now names the branch session');
    assert.deepEqual(f.comments, []);
  });

  test('a takeover of a PR that closes no ticket posts nothing', async () => {
    const f = fakes({ send: archived, prBody: `The work.\n\n${BUILDER}` });
    await f.delivery.deliver({ session: BUILDER }, 'a remark', { source: GITHUB_SOURCE, fallback, takeover: true } as never);
    assert.deepEqual(f.comments, []);
  });
});
