/**
 * A ticket's body edits (#539, under PRD #535). An `issues` `edited`
 * delivery that changes the body reaches the ticket's spec owner and, on a
 * claimed ticket, its builders. The delivery names only a login, and
 * sessions edit as the operator's, so the spec owner is told the edit may
 * be its own and asked to read the body again before it next edits it. The
 * builder is told the spec changed. A title-only edit, and an edit by
 * governor's own App, reach neither role.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { handle } from '../dispatch/webhook/route.mjs';
import { parseFire } from '../dispatch/webhook/fire.mjs';
import { SWITCHES, readConfig, type RepoConfig } from '../dispatch/repo-config.mjs';
import { planTicket } from '../dispatch/ticket-fire.mjs';
import { dispatchMarker } from '../dispatch/webhook/fire.mjs';
import { factoryFile } from './helpers/factory.ts';

const SECRET = 'whsec_test';
const REPO = 'acme/factory';
const OWNERS = ['acme'];
const APP_ID = 5075844;
const CONFIG = (() => {
  const read = readConfig(factoryFile('.github/governor.json'));
  assert.ok(read.ok);
  return read.config as RepoConfig;
})();
const CLAIM = CONFIG.labels.claim;
const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const BUILDER = 'https://claude.ai/code/session_01BUILDER';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const NOW = Date.parse('2026-11-06T12:00:00Z');
const member = { login: 't-d-d', type: 'User' };
const app = { login: 'governor-app[bot]', type: 'Bot' };
const at = { full_name: REPO, default_branch: 'main' };

const sign = (body: string) => `sha256=${createHmac('sha256', SECRET).update(body).digest('hex')}`;

const edited = (labels: string[], { changes = { body: { from: `The old spec.\n\n${SPEC}${FOOTER}` } } as Record<string, unknown>, sender = member as Record<string, unknown>, body = `The spec, with the empty case.\n\n${SPEC}${FOOTER}` } = {}) => ({
  action: 'edited',
  changes,
  issue: {
    number: 7,
    title: 'A ticket',
    state: 'open',
    labels: labels.map((name) => ({ name })),
    html_url: `https://github.com/${REPO}/issues/7`,
    body,
    user: member,
    author_association: 'OWNER',
    assignees: [],
  },
  repository: at,
  sender,
});

const item = (claim: string | undefined, off: string[] = []) => async () => ({
  switches: new Map(SWITCHES.map((name) => [name, !off.includes(name)])),
  ready: ['mode: afk'],
  ...(claim === undefined ? {} : { claim }),
});

const handled = async (payload: unknown, repoItem: () => Promise<unknown>) => {
  const queued: Array<Record<string, any>> = [];
  const deps = {
    secret: async () => SECRET,
    hookSecret: async () => 'hook-secret',
    listedHooks: async () => null,
    countFire: async () => 'counted' as const,
    repoItem,
    owners: OWNERS,
    appId: APP_ID,
    enqueue: async (message: Record<string, unknown>) => { queued.push(message); return `m-${queued.length}`; },
    log: () => {},
  };
  const body = JSON.stringify(payload);
  await handle({ headers: { 'x-github-event': 'issues', 'x-hub-signature-256': sign(body), 'x-github-delivery': 'd-1' }, body, isBase64Encoded: false } as never, deps as never);
  return queued.map((q) => q.fire as Record<string, any>);
};

const ofKind = (fires: Array<Record<string, any>>, kind: string) => fires.filter((f) => f.kind === kind);
/** The fires that reach a role: a message or a ticket fire. */
const toRoles = (fires: Array<Record<string, any>>) => fires.filter((f) => f.kind === 'message' || f.kind === 'ticket');

describe('the receiver: a ticket\'s body edit reaches its roles', () => {
  test('a body edit on a claimed ticket: one ticket fire, an edit, naming the spec owner', async () => {
    const fires = await handled(edited([CLAIM, 'mode: afk']), item(CLAIM));
    assert.deepEqual(ofKind(fires, 'message'), []);
    const [ticket, ...more] = ofKind(fires, 'ticket');
    assert.deepEqual(more, []);
    assert.deepEqual([ticket!.issue, ticket!.event, ticket!.state, ticket!.owner], [7, 'edit', 'open', SPEC]);
    assert.match(ticket!.text, /body of \[#7\]\(https:\/\/github.com\/acme\/factory\/issues\/7\) A ticket was edited by/);
    assert.match(ticket!.text, /t-d-d/);
    assert.deepEqual(parseFire(ticket), ticket);
  });

  test('a body edit on an unclaimed ticket: the spec owner\'s message, told the edit may be its own', async () => {
    const fires = await handled(edited(['mode: afk']), item(CLAIM));
    assert.deepEqual(ofKind(fires, 'ticket'), []);
    const [message, ...more] = ofKind(fires, 'message');
    assert.deepEqual(more, []);
    assert.equal(message!.session, SPEC);
    assert.equal(message!.on, 7);
    assert.match(message!.text, /may be your own/);
    assert.match(message!.text, /read the body again before you next edit it/i);
  });

  test('a body edit on a ticket with no labels reaches its spec owner', async () => {
    const fires = await handled(edited([]), async () => null);
    assert.deepEqual(toRoles(fires).map((f) => [f.kind, f.session]), [['message', SPEC]]);
  });

  test('a title-only edit reaches neither role', async () => {
    const claimed = await handled(edited([CLAIM], { changes: { title: { from: 'Old' } } }), item(CLAIM));
    assert.deepEqual(toRoles(claimed), []);
    const unclaimed = await handled(edited(['mode: afk'], { changes: { title: { from: 'Old' } } }), item(CLAIM));
    assert.deepEqual(toRoles(unclaimed), []);
  });

  test('an edit by governor\'s App reaches neither role', async () => {
    const claimed = await handled(edited([CLAIM], { sender: app }), item(CLAIM));
    assert.deepEqual(toRoles(claimed), []);
    const unclaimed = await handled(edited(['mode: afk'], { sender: app }), item(CLAIM));
    assert.deepEqual(toRoles(unclaimed), []);
  });

  test('with subscribeMessages off, a body edit reaches neither role', async () => {
    const fires = await handled(edited([CLAIM]), item(CLAIM, ['subscribeMessages']));
    assert.deepEqual(toRoles(fires), []);
    const unclaimed = await handled(edited(['mode: afk']), item(CLAIM, ['subscribeMessages']));
    assert.deepEqual(toRoles(unclaimed), []);
  });

  test('a body by an author trust.relay leaves out names no spec owner, and the edit reaches no session', async () => {
    const payload = edited(['mode: afk']);
    const stranger = { ...payload, issue: { ...payload.issue, user: { login: 'stranger', type: 'User' }, author_association: 'NONE' } };
    assert.deepEqual(toRoles(await handled(stranger, item(CLAIM))), []);
  });
});

type Sent = { session: string, text: string };

const context = () => {
  const sent: Sent[] = [];
  const marker = dispatchMarker({ at: new Date(NOW - 60_000).toISOString(), sessionUrl: BUILDER });
  const reader = {
    openClosing: async () => [],
    closure: async () => ({ pr: null }),
    allComments: async () => [{ body: marker, ours: true }],
  };
  const ctx = {
    readerFor: async () => reader,
    configOf: () => CONFIG,
    delivery: () => ({
      ownerOf: async () => ({ session: null }),
      deliver: async ({ session }: { session: string }, text: string) => {
        sent.push({ session, text });
        return { ok: true, answered: true, refused: false, sessionUrl: session, error: null, fallback: null, dropped: null, skipped: null, relinked: null };
      },
    }),
    storeLogin: async () => true,
    now: () => NOW,
    log: () => {},
  };
  return { ctx: ctx as never, sent };
};

const TEXT = 'The body of [#7](https://github.com/acme/factory/issues/7) A ticket was edited by t-d-d.';
const fire = (over: Record<string, unknown> = {}) => ({ kind: 'ticket', repo: REPO, issue: 7, text: TEXT, event: 'edit', state: 'open', labels: [CLAIM], owner: SPEC, authors: ['OWNER'], ...over }) as never;

describe('planTicket: a body edit reaches the spec owner and the builder', () => {
  test('a body edit on a claimed ticket reaches its builder and its spec owner', async () => {
    const { ctx, sent } = context();
    await planTicket(fire(), ctx);
    assert.deepEqual(sent.map((s) => s.session), [SPEC, BUILDER]);
    for (const { text } of sent) assert.ok(text.startsWith(TEXT), text);
  });

  test('the spec owner\'s message says the edit may be its own, and asks it to read the body again', async () => {
    const { ctx, sent } = context();
    await planTicket(fire(), ctx);
    const owner = sent.find((s) => s.session === SPEC)!;
    assert.match(owner.text, /may be your own/);
    assert.match(owner.text, /read the body again before you next edit it/i);
    assert.doesNotMatch(owner.text, /spec changed/i);
  });

  test('the builder\'s message says the spec changed, and to build against the body as it now reads', async () => {
    const { ctx, sent } = context();
    await planTicket(fire(), ctx);
    const builder = sent.find((s) => s.session === BUILDER)!;
    assert.match(builder.text, /spec changed/i);
    assert.match(builder.text, /build against the body as it now reads/i);
    assert.doesNotMatch(builder.text, /may be your own/);
  });

  test('a body edit on an unclaimed ticket reaches its spec owner, told the edit may be its own', async () => {
    const { ctx, sent } = context();
    await planTicket(fire({ labels: ['mode: afk'] }), ctx);
    assert.deepEqual(sent.map((s) => s.session), [SPEC]);
    assert.match(sent[0]!.text, /may be your own/);
    assert.match(sent[0]!.text, /\n\nYou are its spec owner\.$/);
  });

  test('a spec owner that is also the builder hears it once, told both', async () => {
    const { ctx, sent } = context();
    await planTicket(fire({ owner: BUILDER }), ctx);
    assert.deepEqual(sent.map((s) => s.session), [BUILDER]);
    assert.match(sent[0]!.text, /may be your own/);
    assert.match(sent[0]!.text, /spec changed/i);
  });
});
