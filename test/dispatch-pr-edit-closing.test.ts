/**
 * A PR body edit that moves the session link and adds a closing reference
 * is one ordered turn (#626, under PRD #599). Where one `pull_request`
 * `edited` delivery would queue both a `prEdit` fire and a `closingPr`
 * fire, the receiver queues only the `prEdit` fire, marked `closing`. Its
 * turn settles the PR's owner first, then runs the closing check on the
 * body as it now reads, so the dispatch comment names whoever owns the PR:
 *
 * - a live owner's link is written back, and the comment names the owner,
 *   or there is none where the owner already builds the ticket;
 * - an archived owner leaves the editor's link, and the comment names the
 *   editor.
 *
 * An edit that only adds a closing reference queues `closingPr` alone, as
 * before. With `prMessages` or `sessionRules` off no `prEdit` fire runs, so
 * the edit's `closingPr` fire runs in its place.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
import { handle } from '../dispatch/webhook/route.mjs';
import { build, dispatchMarker, dispatchedTo, parseFire } from '../dispatch/webhook/fire.mjs';
import { relinkSession, sessionNamedIn } from '../dispatch/webhook/subscribe.mjs';
import { SWITCHES, readConfig, turnsOn, type RepoConfig } from '../dispatch/repo-config.mjs';
import { planPrEdit } from '../dispatch/take.mjs';
import { planClosingPr } from '../dispatch/ticket-fire.mjs';
import { exitCodeFor } from '../dispatch/cli.mjs';
import { factoryFile } from './helpers/factory.ts';

const SECRET = 'whsec_test';
const REPO = 'acme/factory';
const APP_ID = 5075844;
const NOW = Date.parse('2026-11-06T12:00:00Z');
const CONFIG = (() => {
  const read = readConfig(factoryFile('.github/governor.json'));
  assert.ok(read.ok);
  return read.config as RepoConfig;
})();
const CLAIM = CONFIG.labels.claim;
const OWNER = 'https://claude.ai/code/session_01OWNER';
const EDITOR = 'https://claude.ai/code/session_01EDITOR';
const BUILDER = 'https://claude.ai/code/session_01BUILDER';
const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const member = { login: 't-d-d', type: 'User' };
const at = { full_name: REPO, default_branch: 'main' };
const stamp = (ms = NOW) => new Date(ms).toISOString();

const pr = (session: string, words = 'The work.') => `${words}\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)\n\n${session}`;
const OWNED = pr(OWNER);
/** The editor's body: its link at the end, and a closing reference added. */
const TAKEN = pr(EDITOR, 'The work.\n\nCloses #7');

// ── The receiver ────────────────────────────────────────────────────────

const sign = (body: string) => `sha256=${createHmac('sha256', SECRET).update(body).digest('hex')}`;

const edited = ({ from = OWNED, body = TAKEN } = {}) => ({
  action: 'edited',
  number: 12,
  changes: { body: { from } },
  pull_request: {
    number: 12,
    state: 'open',
    title: 'Build the ticket',
    html_url: `https://github.com/${REPO}/pull/12`,
    body,
    user: member,
    author_association: 'OWNER',
    head: { ref: 'claude/owner', sha: 'a'.repeat(40) },
    base: { ref: 'main' },
    merged: false,
  },
  repository: at,
  sender: member,
});

/** The hook-table item the task writes: every switch on but `off`. */
const item = (off: string[] = []) => async () => ({
  switches: new Map(SWITCHES.map((name) => [name, !off.includes(name)])),
  ready: ['mode: afk'],
  claim: CLAIM,
});

const handled = async (payload: unknown, repoItem: () => Promise<unknown> = item()) => {
  const queued: Array<Record<string, any>> = [];
  const deps = {
    secret: async () => SECRET,
    hookSecret: async () => 'hook-secret',
    listedHooks: async () => null,
    countFire: async () => 'counted' as const,
    repoItem,
    owners: ['acme'],
    appId: APP_ID,
    enqueue: async (message: Record<string, unknown>) => { queued.push(message); return `m-${queued.length}`; },
    log: () => {},
  };
  const body = JSON.stringify(payload);
  await handle({ headers: { 'x-github-event': 'pull_request', 'x-hub-signature-256': sign(body), 'x-github-delivery': 'd-1' }, body, isBase64Encoded: false } as never, deps as never);
  return queued.map((q) => q.fire as Record<string, any>).filter((f) => f.kind === 'prEdit' || f.kind === 'closingPr');
};

describe('the receiver: a PR body edit that moves the link and adds a closing reference', () => {
  test('queues only the prEdit fire, marked as adding a closing reference', async () => {
    const fires = await handled(edited());
    assert.deepEqual(fires.map((f) => f.kind), ['prEdit']);
    assert.equal(fires[0]!.closing, true);
    assert.equal(fires[0]!.from, OWNER);
    assert.equal(fires[0]!.to, EDITOR);
    assert.deepEqual(parseFire(fires[0]), fires[0]);
  });

  test('an edit that only adds a closing reference queues closingPr alone, as before', async () => {
    const fires = await handled(edited({ body: pr(OWNER, 'The work.\n\nCloses #7') }));
    assert.deepEqual(fires, [{ kind: 'closingPr', pr: 12, repo: REPO }]);
  });

  test('an edit that only moves the link queues prEdit with no closing mark', async () => {
    const fires = await handled(edited({ body: pr(EDITOR) }));
    assert.deepEqual(fires.map((f) => f.kind), ['prEdit']);
    assert.equal(fires[0]!.closing, undefined);
  });

  test('a closing reference the old body held already marks nothing', async () => {
    const fires = await handled(edited({ from: pr(OWNER, 'The work.\n\nCloses #7') }));
    assert.deepEqual(fires.map((f) => f.kind), ['prEdit']);
    assert.equal(fires[0]!.closing, undefined);
  });

  test('with prMessages or sessionRules off, the edit queues closingPr as before', async () => {
    for (const off of ['prMessages', 'sessionRules']) {
      assert.deepEqual(await handled(edited(), item([off])), [{ kind: 'closingPr', pr: 12, repo: REPO }], off);
    }
    assert.deepEqual(await handled(edited(), item(['prMessages', 'subscribeMessages'])), []);
  });
});

describe('a prEdit fire marked closing', () => {
  const fire = { ...build.prEdit({ pr: 12, from: OWNER, to: EDITOR, authors: ['OWNER'], closing: true }), repo: REPO };

  test('round-trips, and its mark is true or absent', () => {
    assert.deepEqual(parseFire(JSON.parse(JSON.stringify(fire))), fire);
    assert.throws(() => parseFire({ ...fire, closing: 'yes' }), /closing/);
    assert.equal('closing' in build.prEdit({ pr: 12, from: OWNER, to: EDITOR }), false);
  });
});

// ── The task ────────────────────────────────────────────────────────────

type Sent = { session: string, text: string, opts: Record<string, unknown> };
type Delivery = { ok: boolean, answered: boolean | null, refused: boolean, capped?: boolean, sessionUrl: string | null, error: string | null, fallback: null, dropped: boolean | null, skipped: null, relinked: null };

/**
 * A turn context whose reader holds PR 12, reading `body` until governor
 * writes it, and claimed ticket 7, whose newest dispatch comment names
 * `builder`. The PR's owner is the session its body names, unless that one
 * is `archived`.
 */
const context = ({
  body = TAKEN, builder = BUILDER, archived = [] as string[], capped = [] as string[],
  writeFails = false, config = CONFIG as RepoConfig,
} = {}) => {
  const sent: Sent[] = [];
  const writes: Array<{ pr: number, body: string }> = [];
  const posted: Array<{ issue: number, body: string }> = [];
  const logged: Array<Record<string, unknown>> = [];
  let now = body;
  const reader = {
    pull: async (n: number) => ({ number: n, body: now, head: 'claude/owner', defaultBranch: 'main', open: true, author: 't-d-d', association: 'OWNER' }),
    updatePull: async (n: number, change: { body: string }) => {
      if (writeFails) throw new Error('GitHub answered 403');
      writes.push({ pr: n, body: change.body });
      now = change.body;
    },
    ticket: async (n: number) => ({ number: n, title: 'A ticket', body: `The spec.\n\n${SPEC}${FOOTER}`, state: 'open', labels: [CLAIM], pull: false, author: 't-d-d', association: 'OWNER' }),
    openClosing: async () => [{ number: 12, title: 'PR 12', html_url: 'u12' }],
    closure: async () => ({ pr: null }),
    allComments: async () => [{ id: 1, created_at: stamp(), body: dispatchMarker({ at: stamp(NOW - 3_600_000), sessionUrl: builder }), ours: true }],
    comment: async (n: number, text: string) => { posted.push({ issue: n, body: text }); },
  };
  const answer = (session: string): Delivery => {
    if (capped.includes(session)) return { ok: false, answered: null, refused: false, capped: true, sessionUrl: null, error: 'held at the message ceiling', fallback: null, dropped: null, skipped: null, relinked: null };
    const gone = archived.includes(session);
    return { ok: !gone, answered: true, refused: gone, sessionUrl: session, error: gone ? 'archived' : null, fallback: null, dropped: gone ? true : null, skipped: null, relinked: null };
  };
  const ctx = {
    readerFor: async () => reader,
    configOf: () => config,
    delivery: () => ({
      ownerOf: async (_n: number, read?: { body: string }) => ({ session: sessionNamedIn((read ?? await reader.pull(12)).body), branch: '', linked: true }),
      deliver: async (to: { session?: string }, text: string, opts: Record<string, unknown>) => {
        sent.push({ session: to.session!, text, opts });
        return answer(to.session!);
      },
    }),
    storeLogin: async () => false,
    state: { recordTold: async () => true },
    now: () => NOW,
    log: (event: string, more: Record<string, unknown> = {}) => { logged.push({ event, ...more }); },
  };
  return { ctx: ctx as never, sent, writes, posted, logged };
};

const fire = (over: Record<string, unknown> = {}) => ({ kind: 'prEdit', repo: REPO, pr: 12, from: OWNER, to: EDITOR, authors: ['OWNER'], closing: true, ...over }) as never;
const closing = { closing: planClosingPr };

describe('planPrEdit with a closing reference: the owner is settled before the closing check', () => {
  test('a live owner\'s link is written back, then the dispatch comment names the owner, not the editor', async () => {
    const { ctx, writes, posted } = context();
    const plan = await planPrEdit(fire(), ctx, closing) as any;
    assert.deepEqual(writes, [{ pr: 12, body: relinkSession(TAKEN, OWNER) }]);
    assert.equal(posted.length, 1);
    assert.equal(posted[0]!.issue, 7);
    assert.deepEqual(dispatchedTo(posted[0]!.body), { builder: OWNER, displaced: BUILDER });
    assert.deepEqual(plan.answer.announced, [7]);
    assert.equal(plan.answer.kind, 'prEdit');
    assert.equal(exitCodeFor(plan.answer), 0);
  });

  test('a live owner that builds the ticket already: no dispatch comment', async () => {
    const { ctx, writes, posted } = context({ builder: OWNER });
    await planPrEdit(fire(), ctx, closing);
    assert.equal(writes.length, 1);
    assert.deepEqual(posted, []);
  });

  test('an archived owner: nothing is written, and the dispatch comment names the editor', async () => {
    const { ctx, writes, posted } = context({ archived: [OWNER] });
    await planPrEdit(fire(), ctx, closing);
    assert.deepEqual(writes, []);
    assert.equal(posted.length, 1);
    assert.deepEqual(dispatchedTo(posted[0]!.body), { builder: EDITOR, displaced: BUILDER });
  });

  test('an owner left unsettled runs no closing check: a notice held at the ceiling, or a write that fails', async () => {
    for (const over of [{ capped: [OWNER] }, { writeFails: true }]) {
      const { ctx, posted, logged } = context(over);
      await planPrEdit(fire(), ctx, closing);
      assert.deepEqual(posted, [], JSON.stringify(over));
      assert.ok(logged.some((l) => l.event === 'dispatch-builder' && /not settled/.test(String(l.reason))), JSON.stringify(over));
    }
  });

  test('a prEdit fire with no closing mark runs no closing check', async () => {
    const { ctx, posted } = context();
    await planPrEdit(fire({ closing: undefined }), ctx, closing);
    assert.deepEqual(posted, []);
  });

  test('with subscribeMessages off the owner is settled and no closing check runs', async () => {
    const off = JSON.parse(factoryFile('.github/governor.json'));
    delete off.subscribeMessages;
    const read = readConfig(JSON.stringify(off));
    assert.ok(read.ok);
    assert.equal(turnsOn(read.config as RepoConfig, 'subscribeMessages'), false);
    const { ctx, writes, posted } = context({ config: read.config as RepoConfig });
    await planPrEdit(fire(), ctx, closing);
    assert.equal(writes.length, 1);
    assert.deepEqual(posted, []);
  });
});
