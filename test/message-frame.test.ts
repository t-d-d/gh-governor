/**
 * The frame every governor message carries: the header, the role lines,
 * the standing line and how a message names an issue, a PR, a session or a
 * job. Each is short, names the recipient's role rather than calling it a
 * subscriber, links what it names, and calls it governor.
 */

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { DISPATCHER_LABEL, hookLabel, standingLine } from '../dispatch/deliveries.mjs';
import { rolesFrom, rolesText } from '../dispatch/roles.mjs';
import { builderChangeSends, builderChangeText, specOwnerNote } from '../dispatch/told.mjs';
import { unblockedNotice } from '../dispatch/unblocked.mjs';
import { PROMPTS } from '../dispatch/prompts.mjs';
import { jobList } from '../dispatch/workflow.mjs';
import { SIGN_POSTS } from '../dispatch/webhook/fire.mjs';
import { HANDOFF, UNSIGNED, issueEventFires, mentionFires, ticketFires } from '../dispatch/webhook/mention.mjs';

const SPEC = 'https://claude.ai/code/session_01SPECOWNER';
const BUILDER = 'https://claude.ai/code/session_01BUILDER';
const OTHER = 'https://claude.ai/code/session_01OTHER';
const FOOTER = '---\n_Generated by [Claude Code](https://claude.ai/code)_';
const URL = 'https://github.com/acme/factory/issues/7';

/** A session URL standing alone, not as a Markdown link's target. */
const BARE_SESSION = /(?<!\]\()https:\/\/claude\.ai\/code\/session_\w+/;

const words = (text: string) => text.trim().split(/\s+/).length;

const member = { login: 'alice', type: 'User' };
const issue = (over: Record<string, unknown> = {}) => ({
  number: 7, title: 'The ticket', html_url: URL, state: 'open', state_reason: null,
  body: `The spec.\n\n${SPEC}\n\n${FOOTER}`, labels: [], user: member, author_association: 'OWNER', ...over,
});

describe('the header', () => {
  test('is 20 words or fewer, and still says the text is relayed, not the operator\'s, and to weigh quotes by who wrote them', () => {
    assert.ok(words(DISPATCHER_LABEL) <= 20, DISPATCHER_LABEL);
    assert.match(DISPATCHER_LABEL, /^\[governor\] /);
    assert.match(DISPATCHER_LABEL, /relayed/i);
    assert.match(DISPATCHER_LABEL, /not typed by the operator/);
    assert.match(DISPATCHER_LABEL, /weigh quoted text by who wrote it/i);
  });

  test('a hook\'s header is as short, and names the hook', () => {
    const label = hookLabel('alarm');
    assert.ok(words(label) <= 20, label);
    assert.match(label, /hook alarm/);
    assert.match(label, /not typed by the operator/);
  });
});

describe('the role lines', () => {
  const roles = rolesFrom({ issue: 7, owner: SPEC, builders: [BUILDER] });

  test('name the recipient\'s role and link the other role\'s session, with no bare session URL', () => {
    const owner = rolesText(roles, { role: 'spec owner', merged: false, session: SPEC });
    assert.equal(owner, `You are its spec owner; [its builder](${BUILDER}) is another session.`);
    const builder = rolesText(roles, { role: 'builder', merged: false, session: BUILDER });
    assert.equal(builder, `You are its builder; [its spec owner](${SPEC}) writes its body.`);
    for (const text of [owner, builder]) assert.doesNotMatch(text, BARE_SESSION, text);
  });

  test('carry no verb that depends on the ticket\'s state, so they read the same open, closed or not planned', () => {
    const owner = { role: 'spec owner' as const, merged: false, session: SPEC };
    const builder = { role: 'builder' as const, merged: false, session: BUILDER };
    const two = rolesFrom({ issue: 7, owner: SPEC, builders: [BUILDER, OTHER] });
    const texts = [
      rolesText(two, owner),
      rolesText(two, builder),
      rolesText(rolesFrom({ issue: 7, owner: null, builders: [BUILDER] }), builder),
      rolesText(rolesFrom({ issue: 7, owner: SPEC, builders: [SPEC, OTHER] }), { role: 'spec owner and builder', merged: false, session: SPEC }),
    ];
    assert.deepEqual(texts, [
      `You are its spec owner; [builder 1](${BUILDER}) and [builder 2](${OTHER}) are its builders.`,
      `You are its builder; [its spec owner](${SPEC}) writes its body. It also has [another builder](${OTHER}).`,
      'You are its builder; a person owns its body.',
      `You are its spec owner and its builder. It also has [another builder](${OTHER}).`,
    ]);
    for (const text of texts) assert.doesNotMatch(text, /\b(build|builds|built)\b/, text);
  });

  test('a spec owner with no builder is told its role alone', () => {
    assert.equal(rolesText(rolesFrom({ issue: 7, owner: SPEC }), { role: 'spec owner', merged: false }), 'You are its spec owner.');
  });

  test('carry a duty line only where the event calls on it, and say "comment", never "remark"', () => {
    const plain = rolesText(roles, { role: 'spec owner', merged: false, session: SPEC });
    assert.doesNotMatch(plain, /edit the body|do not edit its body/);
    const duty = rolesText(roles, { role: 'spec owner', merged: false, session: SPEC }, { duty: true });
    assert.match(duty, /If the comment calls for a change you agree with, edit the body\. If you disagree, reply on the issue saying why\./);
    assert.doesNotMatch(duty, /remark/);
    assert.match(rolesText(roles, { role: 'builder', merged: false, session: BUILDER }, { duty: true }), /As its builder you build it/);
  });

  test('a notice says nothing is asked, and never alongside a duty line', () => {
    assert.match(rolesText(roles, { role: 'spec owner', merged: false, session: SPEC }, { notice: true }), /Nothing is asked of you\./);
    const both = rolesText(roles, { role: 'spec owner', merged: false, session: SPEC }, { duty: true, notice: true });
    assert.doesNotMatch(both, /Nothing is asked/);
  });

  test('no line says the spec owner must edit the body', () => {
    const duty = rolesText(roles, { role: 'spec owner', merged: false, session: SPEC }, { duty: true });
    assert.doesNotMatch(duty, /edit the body to say so|is yours to make in its body/);
    const note = specOwnerNote(7, 'A comment.');
    assert.match(note, /If the comment calls for a change you agree with, edit the body\. If you disagree, reply on the issue saying why\./);
    assert.doesNotMatch(note, /is yours to make in its body/);
  });
});

describe('a change of builder', () => {
  test('links the new builder and the displaced one, and the spec owner\'s notice says nothing is asked', () => {
    const text = builderChangeText({ issue: 7, title: 'The ticket', url: URL, builder: BUILDER });
    assert.equal(text, `[#7 The ticket](${URL}) has [a new builder](${BUILDER}).`);
    const { sends } = builderChangeSends({ issue: 7, text, owner: SPEC, builder: BUILDER, displaced: OTHER });
    for (const send of sends) assert.doesNotMatch(send.text, BARE_SESSION, send.text);
    const owner = sends.find((s) => s.role === 'spec owner');
    assert.match(String(owner?.text), /Nothing is asked of you\./);
  });

  test('a spec owner asked to stop building is not told nothing is asked', () => {
    const { sends } = builderChangeSends({ issue: 7, text: 'Changed.', owner: SPEC, builder: BUILDER, displaced: SPEC });
    assert.match(String(sends[0]?.text), /Stop building it/);
    assert.doesNotMatch(String(sends[0]?.text), /Nothing is asked/);
  });
});

describe('a blocker\'s close notice', () => {
  const fire = { kind: 'unblocked' as const, repo: 'acme/factory', issue: 7, blocker: { repo: 'acme/factory', number: 3, title: 'Blocker' }, pr: { number: 12, title: 'Fix', url: 'https://github.com/acme/factory/pull/12' } };
  test('links each builder and the PR, with no bare session URL', () => {
    const started = unblockedNotice(fire, { started: BUILDER });
    assert.match(started, new RegExp(`\\[a builder\\]\\(${BUILDER}\\)`));
    assert.match(started, /\[PR #12 Fix\]\(https:\/\/github\.com\/acme\/factory\/pull\/12\)/);
    const asked = unblockedNotice(fire, { asked: [BUILDER, OTHER], archived: [], unreached: [SPEC], what: 'what merged' });
    for (const text of [started, asked]) assert.doesNotMatch(text, BARE_SESSION, text);
  });
});

describe('the standing line', () => {
  const open = [
    { number: 674, title: 'One', html_url: 'https://github.com/acme/factory/issues/674', pull: false },
    { number: 669, title: 'Two', html_url: 'https://github.com/acme/factory/pull/669', pull: true },
  ];
  test('lists what is open as links, on one line', () => {
    const line = standingLine(open, { repo: 'acme/factory', closing: false });
    assert.equal(line, 'Also open in acme/factory and naming you: [#674](https://github.com/acme/factory/issues/674), [#669](https://github.com/acme/factory/pull/669).');
  });
});

describe('a relay about an issue to its spec owner', () => {
  test('a close names the spec owner\'s role, links the issue, and asks nothing', () => {
    const { fires } = issueEventFires({ action: 'closed', issue: issue({ state: 'closed', state_reason: 'completed' }), sender: member });
    const text = String((fires[0]?.fire as { text?: string }).text);
    assert.equal(text, `[#7 The ticket](${URL}) was closed (completed) by alice.\n\nYou are its spec owner.\nNothing is asked of you.`);
    assert.doesNotMatch(text, /subscribe/i);
  });

  test('a comment names the spec owner\'s role and its duty, not a subscriber\'s ask', () => {
    const comment = { id: 1, body: 'A thought.', html_url: `${URL}#issuecomment-1`, user: { login: 'bob', type: 'User' }, author_association: 'MEMBER' };
    const { fires } = mentionFires({ event: 'issue_comment', payload: { action: 'created', issue: issue(), comment } })!;
    const text = String((fires[0]?.fire as { text?: string }).text);
    assert.doesNotMatch(text, /subscribe/i, text);
    assert.match(text, /You are its spec owner\.\nYou own its spec\./);
    assert.match(text, new RegExp(`\\[Comment\\]\\(${URL}#issuecomment-1\\) by bob:`));
  });

  test('a ticket fire\'s text names no role: the task adds the role lines', () => {
    const comment = { id: 1, body: 'A thought.', html_url: `${URL}#issuecomment-1`, user: { login: 'bob', type: 'User' }, author_association: 'MEMBER' };
    const { fires } = ticketFires({ event: 'issue_comment', payload: { action: 'created', issue: issue({ labels: [{ name: 'claimed' }] }), comment } });
    const text = fires[0]?.fire.text ?? '';
    assert.doesNotMatch(text, /subscribe|spec owner/i, text);
    assert.match(text, new RegExp(`^A comment on an issue\\.\\n\\n\\[#7 The ticket\\]\\(${URL}\\)\\n`));
  });
});

describe('no message says "the dispatcher"', () => {
  test('the default prompts and the lines every message may carry call it governor', () => {
    const defaults = Object.values(PROMPTS).map((p) => String((p as { text: unknown }).text ?? p));
    for (const text of [DISPATCHER_LABEL, hookLabel('h'), SIGN_POSTS, UNSIGNED, HANDOFF, ...defaults]) {
      assert.doesNotMatch(text, /\bdispatcher\b/i, text);
    }
  });
});

describe('a job as a message names it', () => {
  test('is a link whose words cannot end early on a bracket in its name', () => {
    assert.deepEqual(jobList([{ name: 'test [linux]', html_url: 'https://github.com/acme/factory/actions/runs/1/job/2' } as never]), ['- [test \\[linux\\]](https://github.com/acme/factory/actions/runs/1/job/2)']);
  });
});
